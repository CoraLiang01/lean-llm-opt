import gurobipy as gp
from gurobipy import GRB
m = gp.Model()
records = CSVQA_DATA['logical_records']
benefit = {}
item_fee = {}
category_params = {}
bundle_params = {}
incompatible_pairs = []
requires_pairs = []
usage_dict = {}
capacity_dict = {}
item_params = {}

def to_int(val):
    try:
        return int(val)
    except Exception:
        return 0
for rec in records.get('benefit', []):
    vals = rec['values']
    item = vals['item_ref']
    amt = to_int(vals['amount_cents'])
    benefit[item] = benefit.get(item, 0) + amt
for rec in records.get('item_fee', []):
    vals = rec['values']
    item = vals['item_ref']
    item_fee[item] = to_int(vals['activation_fee_cents'])
for rec in records.get('category', []):
    vals = rec['values']
    cat = vals['category']
    category_params[cat] = {'activation_fee_cents': to_int(vals['activation_fee_cents']), 'minimum_quantity': to_int(vals['minimum_quantity']), 'maximum_quantity': to_int(vals['maximum_quantity'])}
for rec in records.get('bundle', []):
    vals = rec['values']
    key = (vals['item_a'], vals['item_b'])
    bundle_params[key] = to_int(vals['bonus_cents'])
for rec in records.get('incompatible', []):
    vals = rec['values']
    incompatible_pairs.append((vals['item_a'], vals['item_b']))
for rec in records.get('requires', []):
    vals = rec['values']
    requires_pairs.append((vals['item_ref'], vals['prerequisite_ref']))
for rec in records.get('usage', []):
    vals = rec['values']
    item = vals['item_ref']
    res = vals['resource']
    amt = to_int(vals['amount'])
    usage_dict[item, res] = amt
for rec in records.get('capacity_ledger', []):
    vals = rec['values']
    res = vals['resource']
    amt = to_int(vals['amount'])
    capacity_dict[res] = capacity_dict.get(res, 0) + amt
for fam in ('item',):
    for rec in records.get(fam, []):
        vals = rec['values']
        item = vals['item_ref']
        item_params[item] = {'category': vals['category'], 'authorized': to_int(vals['authorized']), 'minimum_lot': to_int(vals['minimum_lot']), 'maximum_order': to_int(vals['maximum_order']), 'location_id': vals['location_id']}
item_ids = list(item_params.keys())
category_ids = list(category_params.keys())
resource_ids = list(capacity_dict.keys())
bundle_keys = list(bundle_params.keys())
x = {i: m.addVar(vtype=GRB.INTEGER, name=f'x_{i}') for i in item_ids}
y = {i: m.addVar(vtype=GRB.BINARY, name=f'y_{i}') for i in item_ids}
z = {c: m.addVar(vtype=GRB.BINARY, name=f'z_{c}') for c in category_ids}
w = {b: m.addVar(vtype=GRB.BINARY, name=f'w_{b[0]}_{b[1]}') for b in bundle_keys}
for r in resource_ids:
    expr = gp.LinExpr()
    for i in item_ids:
        usage = usage_dict.get((i, r), 0)
        if usage != 0:
            expr += usage * x[i]
    m.addConstr(expr <= capacity_dict[r], name=f'cap_{r}')
for i in item_ids:
    params = item_params[i]
    u = params['maximum_order']
    l = params['minimum_lot']
    f = params['authorized']
    m.addConstr(x[i] <= u * y[i], name=f'max_{i}')
    m.addConstr(x[i] >= l * y[i], name=f'min_{i}')
    m.addConstr(y[i] <= f, name=f'auth_{i}')
for c in category_ids:
    for i in item_ids:
        if item_params[i]['category'] == c:
            m.addConstr(z[c] >= y[i], name=f'cat_link_{c}_{i}')
for c in category_ids:
    params = category_params[c]
    qmin = params['minimum_quantity']
    qmax = params['maximum_quantity']
    expr = gp.LinExpr()
    for i in item_ids:
        if item_params[i]['category'] == c:
            expr += x[i]
    m.addConstr(expr >= qmin * z[c], name=f'cat_min_{c}')
    m.addConstr(expr <= qmax * z[c], name=f'cat_max_{c}')
for a, b in incompatible_pairs:
    if a in y and b in y:
        m.addConstr(y[a] + y[b] <= 1, name=f'incomp_{a}_{b}')
for req, prereq in requires_pairs:
    if req in y and prereq in y:
        m.addConstr(y[req] <= y[prereq], name=f'req_{req}_{prereq}')
for (a, b), bonus in bundle_params.items():
    if a in y and b in y:
        m.addConstr(w[a, b] <= y[a], name=f'bundle_left_{a}_{b}')
        m.addConstr(w[a, b] <= y[b], name=f'bundle_right_{a}_{b}')
        m.addConstr(w[a, b] >= y[a] + y[b] - 1, name=f'bundle_link_{a}_{b}')
obj = gp.LinExpr()
for i in item_ids:
    obj += benefit.get(i, 0) * x[i]
    obj -= item_fee.get(i, 0) * y[i]
for c in category_ids:
    obj -= category_params[c]['activation_fee_cents'] * z[c]
for b, bonus in bundle_params.items():
    obj += bonus * w[b]
m.setObjective(obj, GRB.MAXIMIZE)
m.setParam('MIPGap', 1e-06)
m.optimize()