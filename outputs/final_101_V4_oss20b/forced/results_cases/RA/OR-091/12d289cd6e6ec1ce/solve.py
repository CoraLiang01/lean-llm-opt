import gurobipy as gp
from gurobipy import GRB
records = CSVQA_DATA['tables'][0]['records']
m = gp.Model('OperationsResearchCourses')
m.setParam('MIPGap', 1e-06)
y = {}
for rec in records:
    cid = rec['values']['course_id']
    y[cid] = m.addVar(vtype=GRB.BINARY)
m.update()
obj = gp.quicksum((int(rec['values']['interest_points']) * y[rec['values']['course_id']] for rec in records))
m.setObjective(obj, GRB.MAXIMIZE)
credit_con = gp.quicksum((int(rec['values']['credits']) * y[rec['values']['course_id']] for rec in records))
m.addConstr(credit_con <= 20)
m.optimize()
if m.status == GRB.OPTIMAL:
    print('Objective Value:', m.objVal)
    for rec in records:
        cid = rec['values']['course_id']
        var = y[cid]
        print(f'{var.VarName} = {var.X}')
else:
    print('Solver Status:', m.status)