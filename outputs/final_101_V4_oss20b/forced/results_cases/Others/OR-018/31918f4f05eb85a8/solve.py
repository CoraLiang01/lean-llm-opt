import gurobipy
from gurobipy import GRB

def solve_problem():
    m = gurobipy.Model()
    m.setParam('MIPGap', 1e-06)
    table = None
    for tbl in CSVQA_DATA['tables']:
        if tbl.get('table_id') == 'file_0_view_0':
            table = tbl
            break
    if table is None:
        raise ValueError("Required table 'file_0_view_0' not found in CSVQA_DATA")
    records = table.get('records', [])
    I = [rec['source_row'] for rec in records]
    revenue = {}
    demand = {}
    initial = {}
    for rec in records:
        i = rec['source_row']
        vals = rec['values']
        try:
            revenue[i] = float(vals['Revenue'])
            demand[i] = int(vals['Demand'])
            initial[i] = int(vals['Initial Inventory'])
        except KeyError as e:
            raise ValueError(f'Missing parameter {e} for record {i}')
    x = m.addVars(I, vtype=GRB.INTEGER, name='')
    m.setObjective(gurobipy.quicksum((revenue[i] * x[i] for i in I)), GRB.MAXIMIZE)
    for i in I:
        m.addConstr(x[i] <= demand[i], name=f'Demand_{i}')
        m.addConstr(x[i] <= initial[i], name=f'Initial_{i}')
    m.optimize()
    return m
m = solve_problem()