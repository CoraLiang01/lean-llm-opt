import gurobipy
from gurobipy import GRB

def solve_problem():
    table_id = 'file_0_view_0'
    table = None
    for tbl in CSVQA_DATA['tables']:
        if tbl.get('table_id') == table_id:
            table = tbl
            break
    if table is None:
        raise ValueError(f'Table {table_id} not found in CSVQA_DATA')
    records = table.get('records', [])
    if not records:
        raise ValueError(f'No records found in table {table_id}')
    indices = []
    revenue = {}
    demand = {}
    inventory = {}
    for rec in records:
        values = rec.get('values', {})
        prod_ref = values.get('Product_Reference')
        if prod_ref is None:
            raise ValueError(f'Missing Product_Reference in record {rec.get('source_row')}')
        indices.append(prod_ref)
        rev_str = values.get('Revenue')
        dem_str = values.get('Demand')
        inv_str = values.get('Initial Inventory')
        if rev_str is None or dem_str is None or inv_str is None:
            raise ValueError(f'Missing parameter in record {rec.get('source_row')}')
        try:
            rev = float(rev_str)
            dem = int(dem_str)
            inv = float(inv_str)
        except ValueError as e:
            raise ValueError(f'Invalid numeric value in record {rec.get('source_row')}: {e}')
        revenue[prod_ref] = rev
        demand[prod_ref] = dem
        inventory[prod_ref] = inv
    m = gurobipy.Model()
    m.setParam('MIPGap', 1e-06)
    x = m.addVars(indices, vtype=GRB.INTEGER, name='')
    m.setObjective(gurobipy.quicksum((revenue[i] * x[i] for i in indices)), GRB.MAXIMIZE)
    m.addConstrs((x[i] <= demand[i] for i in indices), name='')
    m.addConstrs((x[i] <= inventory[i] for i in indices), name='')
    m.optimize()
    return m
m = solve_problem()