import gurobipy as gp
from gurobipy import GRB
import numpy as np
data = CSVQA_DATA
tables = data['tables']
demand_table = next((t for t in tables if t['table_id'] == 'file_0_view_0'))
supply_table = next((t for t in tables if t['table_id'] == 'file_1_view_0'))
cost_table = next((t for t in tables if t['table_id'] == 'file_2_view_0'))
customers = []
demands = []
for rec in demand_table['records']:
    customers.append(rec['values']['customer'])
    demands.append(int(rec['values']['demand']))
suppliers = []
supplies = []
for rec in supply_table['records']:
    suppliers.append(rec['values']['Unnamed: 0'])
    supplies.append(int(rec['values']['supply_capacity']))
n_sup = len(suppliers)
n_cus = len(customers)
cost_matrix = np.zeros((n_sup, n_cus), dtype=float)
for i, rec in enumerate(cost_table['records']):
    for j, cust in enumerate(customers):
        cost_matrix[i, j] = float(rec['values'][cust])
m = gp.Model('Transportation')
m.Params.MIPGap = 1e-06
x = m.addVars(n_sup, n_cus, vtype=GRB.CONTINUOUS)
m.setObjective(gp.quicksum((cost_matrix[i, j] * x[i, j] for i in range(n_sup) for j in range(n_cus))), GRB.MINIMIZE)
for i in range(n_sup):
    m.addConstr(gp.quicksum((x[i, j] for j in range(n_cus))) <= supplies[i])
for j in range(n_cus):
    m.addConstr(gp.quicksum((x[i, j] for i in range(n_sup))) == demands[j])
m.optimize()
if m.Status == GRB.OPTIMAL:
    print(f'Objective value: {m.ObjVal}')
    for var in m.getVars():
        print(f'{var.VarName} = {var.X}')
else:
    print(f'Solver status: {m.Status}')