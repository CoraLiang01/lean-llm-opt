import gurobipy
from gurobipy import GRB

def solve_problem():
    table_id = 'file_0_view_0'
    tables = CSVQA_DATA.get('tables', [])
    target_table = None
    for tbl in tables:
        if tbl.get('table_id') == table_id:
            target_table = tbl
            break
    if target_table is None:
        raise ValueError(f"Table '{table_id}' not found in CSVQA_DATA")
    records = target_table.get('records', [])
    if not records:
        raise ValueError(f"No records found in table '{table_id}'")
    I = []
    r_i = {}
    d_i = {}
    v_i = {}
    for rec in records:
        vals = rec.get('values', {})
        prod_ref = vals.get('Product_Reference')
        if prod_ref is None:
            raise ValueError('Missing Product_Reference in a record')
        if prod_ref in I:
            raise ValueError(f"Duplicate Product_Reference '{prod_ref}'")
        I.append(prod_ref)
        try:
            revenue = float(vals['Revenue'])
        except (KeyError, ValueError):
            raise ValueError(f"Missing or invalid Revenue for '{prod_ref}'")
        try:
            demand = float(vals['Demand'])
        except (KeyError, ValueError):
            raise ValueError(f"Missing or invalid Demand for '{prod_ref}'")
        try:
            inventory = float(vals['Initial Inventory'])
        except (KeyError, ValueError):
            raise ValueError(f"Missing or invalid Initial Inventory for '{prod_ref}'")
        r_i[prod_ref] = revenue
        d_i[prod_ref] = demand
        v_i[prod_ref] = inventory
    model = gurobipy.Model()
    model.setParam('MIPGap', 1e-06)
    x = model.addVars(I, lb=0, vtype=GRB.CONTINUOUS, name='')
    for i in I:
        model.addConstr(x[i] <= d_i[i], name=f'demand_{i}')
        model.addConstr(x[i] <= v_i[i], name=f'inventory_{i}')
    model.setObjective(gurobipy.quicksum((r_i[i] * x[i] for i in I)), GRB.MAXIMIZE)
    model.optimize()
    return model
m = solve_problem()