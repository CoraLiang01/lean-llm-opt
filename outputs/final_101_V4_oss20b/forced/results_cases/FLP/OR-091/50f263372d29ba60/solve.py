import gurobipy as gp
from gurobipy import GRB
tables = CSVQA_DATA['tables']
records = None
for t in tables:
    if t.get('table_id') == 'file_0_view_0':
        records = t['records']
        break
if records is None:
    raise ValueError('Required table not found')
course_ids = []
credits = {}
interest_points = {}
for rec in records:
    vals = rec['values']
    cid = vals['course_id']
    course_ids.append(cid)
    credits[cid] = int(vals['credits'])
    interest_points[cid] = int(vals['interest_points'])
m = gp.Model('Operations_Research_Course_Selection')
m.Params.MIPGap = 1e-06
x = m.addVars(course_ids, vtype=GRB.BINARY)
m.setObjective(gp.quicksum((interest_points[c] * x[c] for c in course_ids)), GRB.MAXIMIZE)
m.addConstr(gp.quicksum((credits[c] * x[c] for c in course_ids)) <= 20)
m.optimize()
if m.Status == GRB.OPTIMAL:
    print('Optimal objective value:', m.ObjVal)
    for c in course_ids:
        print(f'{x[c].VarName} = {x[c].X}')
else:
    print('Solver status:', m.Status)