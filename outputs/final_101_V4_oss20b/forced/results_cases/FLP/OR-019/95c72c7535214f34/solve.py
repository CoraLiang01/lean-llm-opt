import gurobipy
from gurobipy import GRB

def solve_problem():
    tables = CSVQA_DATA['tables']
    target_table = None
    for tbl in tables:
        if tbl.get('table_id') == 'file_0_view_0':
            target_table = tbl
            break
    if target_table is None:
        raise ValueError("Required table 'file_0_view_0' not found in CSVQA_DATA")
    r = {}
    d = {}
    s = {}
    I = []
    for rec in target_table['records']:
        values = rec['values']
        for col in ['Product Name', 'Revenue', 'Demand', 'Initial Inventory']:
            if col not in values:
                raise ValueError(f"Missing column '{col}' in record {rec}")
        prod_name = values['Product Name'].strip()
        if prod_name in r:
            raise ValueError(f"Duplicate product identifier '{prod_name}'")
        try:
            revenue = float(values['Revenue'])
            demand = float(values['Demand'])
            inventory = float(values['Initial Inventory'])
        except ValueError as e:
            raise ValueError(f'Non-numeric value in record {rec}: {e}')
        r[prod_name] = revenue
        d[prod_name] = demand
        s[prod_name] = inventory
        I.append(prod_name)
    m = gurobipy.Model('27in_product_revenue_maximization')
    m.setParam('MIPGap', 1e-06)
    x = m.addVars(I, lb=0, vtype=GRB.CONTINUOUS, name='')
    m.setObjective(gurobipy.quicksum((r[i] * x[i] for i in I)), GRB.MAXIMIZE)
    m.addConstrs((x[i] <= d[i] for i in I), name='')
    m.addConstrs((x[i] <= s[i] for i in I), name='')
    m.optimize()
    return m
m = solve_problem()