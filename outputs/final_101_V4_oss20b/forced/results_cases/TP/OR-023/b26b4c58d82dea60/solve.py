import gurobipy
from gurobipy import GRB

def solve_problem():
    table = CSVQA_DATA['tables'][0]
    records = table['records']
    product_refs = []
    revenue_dict = {}
    demand_dict = {}
    inventory_dict = {}
    for rec in records:
        vals = rec['values']
        prod_ref = vals['Product_Reference']
        if 'Revenue' not in vals or 'Demand' not in vals or 'Initial Inventory' not in vals:
            raise ValueError(f'Missing parameter in record {rec['source_row']}')
        try:
            rev = float(vals['Revenue'])
            dem = float(vals['Demand'])
            inv = float(vals['Initial Inventory'])
        except ValueError as e:
            raise ValueError(f'Invalid numeric value in record {rec['source_row']}: {e}')
        product_refs.append(prod_ref)
        revenue_dict[prod_ref] = rev
        demand_dict[prod_ref] = dem
        inventory_dict[prod_ref] = inv
    model = gurobipy.Model()
    model.setParam('MIPGap', 1e-06)
    x = model.addVars(product_refs, lb=0, vtype=GRB.CONTINUOUS, name='')
    model.setObjective(gurobipy.quicksum((revenue_dict[i] * x[i] for i in product_refs)), GRB.MAXIMIZE)
    for i in product_refs:
        model.addConstr(x[i] <= demand_dict[i], name=f'demand_{i}')
        model.addConstr(x[i] <= inventory_dict[i], name=f'inventory_{i}')
    model.optimize()
    return model
