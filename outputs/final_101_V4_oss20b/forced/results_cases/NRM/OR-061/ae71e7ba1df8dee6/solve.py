import gurobipy
from gurobipy import GRB

def solve_problem():
    tables = CSVQA_DATA['tables']
    demand_table = next((t for t in tables if t['table_id'] == 'file_0_view_0'))
    fixed_cost_table = next((t for t in tables if t['table_id'] == 'file_1_view_0'))
    transport_table = next((t for t in tables if t['table_id'] == 'file_2_view_0'))
    demand = {}
    for rec in demand_table['records']:
        cust = rec['values']['customer']
        val = float(rec['values']['demand'])
        demand[cust] = val
    fixed_cost = {}
    for rec in fixed_cost_table['records']:
        sup = rec['values']['Unnamed: 0']
        val = float(rec['values']['fixed_costs'])
        fixed_cost[sup] = val
    transport_cost = {}
    for rec in transport_table['records']:
        sup = rec['values']['Unnamed: 0']
        for cust in demand.keys():
            key = (sup, cust)
            val = float(rec['values'][cust])
            transport_cost[key] = val
    suppliers = set(fixed_cost.keys())
    customers = set(demand.keys())
    if suppliers != set((s for s, _ in transport_cost.keys())):
        missing = suppliers - set((s for s, _ in transport_cost.keys()))
        raise ValueError(f'Missing transport data for suppliers: {missing}')
    for sup in suppliers:
        for cust in customers:
            if (sup, cust) not in transport_cost:
                raise ValueError(f'Missing transport cost for supplier {sup} to customer {cust}')
    M = sum(demand.values())
    m = gurobipy.Model()
    m.setParam('MIPGap', 1e-06)
    y = m.addVars(suppliers, vtype=GRB.BINARY, name='')
    x = m.addVars([(s, c) for s in suppliers for c in customers], vtype=GRB.CONTINUOUS, lb=0, name='')
    obj = gurobipy.quicksum((fixed_cost[s] * y[s] for s in suppliers)) + gurobipy.quicksum((transport_cost[s, c] * x[s, c] for s in suppliers for c in customers))
    m.setObjective(obj, GRB.MINIMIZE)
    for c in customers:
        m.addConstr(gurobipy.quicksum((x[s, c] for s in suppliers)) >= demand[c], name=f'demand_{c}')
    for s in suppliers:
        for c in customers:
            m.addConstr(x[s, c] <= M * y[s], name=f'link_{s}_{c}')
    m.optimize()
    return m
m = solve_problem()