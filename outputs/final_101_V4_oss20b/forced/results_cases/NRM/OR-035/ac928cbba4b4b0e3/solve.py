import gurobipy
from gurobipy import GRB

def solve_problem():
    tables = CSVQA_DATA['tables']
    cap_table = next((t for t in tables if t['table_id'] == 'file_0_view_0'))
    cap_record = cap_table['records'][0]
    C = float(cap_record['values']['Capacity'])
    prod_table = next((t for t in tables if t['table_id'] == 'file_1_view_0'))
    I = []
    p = {}
    w = {}
    for rec in prod_table['records']:
        prod = rec['values']['ProductName']
        I.append(prod)
        val_str = rec['values']['Value']
        wt_str = rec['values']['Weight']
        if val_str is None or wt_str is None:
            raise ValueError(f'Missing Value or Weight for product {prod}')
        p[prod] = float(val_str)
        w[prod] = float(wt_str)
    m = gurobipy.Model()
    m.setParam('MIPGap', 1e-06)
    x = m.addVars(I, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gurobipy.quicksum((p[i] * x[i] for i in I)), GRB.MAXIMIZE)
    m.addConstr(gurobipy.quicksum((w[i] * x[i] for i in I)) <= C, name='capacity')
    m.optimize()
    return m
m = solve_problem()