import gurobipy
from gurobipy import GRB

def solve_problem():
    data = CSVQA_DATA
    table = None
    for t in data['tables']:
        if t['table_id'] == 'file_0_view_0':
            table = t
            break
    if table is None:
        raise ValueError("Required table 'file_0_view_0' not found in CSVQA_DATA")
    records = table['records']
    I = set()
    r = {}
    d = {}
    Iinv = {}
    for rec in records:
        prod = rec['values']['Product Name']
        if prod in I:
            raise ValueError(f'Duplicate product name detected: {prod}')
        I.add(prod)
        try:
            rev = float(rec['values']['Revenue'])
        except Exception:
            raise ValueError(f'Invalid Revenue value for product {prod}')
        try:
            dem = int(rec['values']['Demand'])
        except Exception:
            raise ValueError(f'Invalid Demand value for product {prod}')
        try:
            inv = int(rec['values']['Initial Inventory'])
        except Exception:
            raise ValueError(f'Invalid Initial Inventory value for product {prod}')
        r[prod] = rev
        d[prod] = dem
        Iinv[prod] = inv
    for prod in I:
        if prod not in r or prod not in d or prod not in Iinv:
            raise ValueError(f'Missing parameter for product {prod}')
    m = gurobipy.Model()
    m.setParam('MIPGap', 1e-06)
    x = m.addVars(I, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gurobipy.quicksum((r[i] * x[i] for i in I)), GRB.MAXIMIZE)
    m.addConstrs((x[i] <= d[i] for i in I), name='')
    m.addConstrs((x[i] <= Iinv[i] for i in I), name='')
    m.optimize()
    return m
m = solve_problem()
