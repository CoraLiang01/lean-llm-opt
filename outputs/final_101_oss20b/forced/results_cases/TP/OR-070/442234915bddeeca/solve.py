import gurobipy as gp
from gurobipy import GRB
import pandas as pd
table = CSVQA_DATA['tables'][0]
records = table['records']
df = pd.DataFrame([rec['values'] for rec in records])
managers = df['Manager'].tolist()
proj_cols = [col for col in df.columns if col != 'Manager']
projects = []
for col in proj_cols:
    num = col.split()[1]
    projects.append(f'Project {num}')
cost = {}
for _, row in df.iterrows():
    m = row['Manager']
    cost[m] = {}
    for col in proj_cols:
        p = col.split()[1]
        cost[m][f'Project {p}'] = float(row[col])
m = gp.Model('assignment')
m.setParam(GRB.Param.MIPGap, 1e-06)
x = {}
for i, mi in enumerate(managers):
    for j, pj in enumerate(projects):
        var = m.addVar(vtype=GRB.BINARY)
        x[mi, pj] = var
m.update()
for i, mi in enumerate(managers):
    m.addConstr(gp.quicksum((x[mi, pj] for pj in projects)) == 1)
for j, pj in enumerate(projects):
    m.addConstr(gp.quicksum((x[mi, pj] for mi in managers)) == 1)
m.setObjective(gp.quicksum((cost[mi][pj] * x[mi, pj] for mi in managers for pj in projects)), GRB.MINIMIZE)
m.optimize()
if m.status == GRB.OPTIMAL:
    print(f'Objective: {m.objVal}')
    for var in m.getVars():
        if var.X > 0:
            print(f'{var.VarName} = {var.X}')
else:
    print(f'Solver status: {m.status}')