CSVQA_FRAMES = {t["table_id"]: pd.DataFrame([r["values"] for r in t["records"]], columns=t["columns"], index=[r["source_row"] for r in t["records"]]) for t in CSVQA_DATA["tables"]}
import gurobipy as gp
from gurobipy import GRB

def solve_problem(CSVQA_FRAMES):
    import pandas as pd
    shelves_df = CSVQA_FRAMES['file_0_view_0']
    products_df = CSVQA_FRAMES['file_1_view_0']
    shelves = []
    shelf_capacity = {}
    for (idx, row) in shelves_df.iterrows():
        shelf_id = row['resource_id']
        shelves.append(shelf_id)
        try:
            cap = float(row['resource_capacity'])
        except Exception:
            raise ValueError(f"Invalid resource_capacity for shelf {shelf_id}: {row['resource_capacity']}")
        shelf_capacity[shelf_id] = cap
    products = []
    product_value = {}
    product_requirement = {}
    for (idx, row) in products_df.iterrows():
        prod_id = row['item_name']
        products.append(prod_id)
        try:
            val = float(row['item_value'])
        except Exception:
            raise ValueError(f"Invalid item_value for product {prod_id}: {row['item_value']}")
        try:
            req = float(row['resource_requirement'])
        except Exception:
            raise ValueError(f"Invalid resource_requirement for product {prod_id}: {row['resource_requirement']}")
        product_value[prod_id] = val
        product_requirement[prod_id] = req
    if len(shelves) == 0 or len(products) == 0:
        raise ValueError('No shelves or products found in input data.')
    m = gp.Model('BigMart_Shelf_Allocation')
    quantity_keys = [(i, j) for i in shelves for j in products]
    quantity_vars = m.addVars(quantity_keys, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((product_value[j] * quantity_vars[i, j] for i in shelves for j in products)), GRB.MAXIMIZE)
    for i in shelves:
        m.addConstr(gp.quicksum((product_requirement[j] * quantity_vars[i, j] for j in products)) <= shelf_capacity[i], name=f'cap_{i}')
    m.Params.MIPGap = 0.0001
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for var in m.getVars():
            print(f'{var.VarName}: {var.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem(CSVQA_FRAMES)