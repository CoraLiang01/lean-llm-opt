import pandas as pd
CSVQA_FRAMES = {t["table_id"]: pd.DataFrame([r["values"] for r in t["records"]], columns=t["columns"], index=[r["source_row"] for r in t["records"]]) for t in CSVQA_DATA["tables"]}
import gurobipy as gp
from gurobipy import GRB

def solve_problem(CSVQA_FRAMES):
    import pandas as pd
    demand_df = CSVQA_FRAMES['file_0_view_0']
    fixed_cost_df = CSVQA_FRAMES['file_1_view_0']
    cost_df = CSVQA_FRAMES['file_2_view_0']
    I = list(fixed_cost_df['Unnamed: 0'])
    J = list(demand_df['customer'])
    d_j = {}
    for (_, row) in demand_df.iterrows():
        j = row['customer']
        try:
            d_j[j] = float(row['demand'])
        except Exception:
            raise ValueError(f"Non-numeric demand for customer {j}: {row['demand']}")
    f_i = {}
    for (_, row) in fixed_cost_df.iterrows():
        i = row['Unnamed: 0']
        try:
            f_i[i] = float(row['fixed_costs'])
        except Exception:
            raise ValueError(f"Non-numeric fixed cost for supplier {i}: {row['fixed_costs']}")
    c_ij = {}
    for (_, row) in cost_df.iterrows():
        i = row['Unnamed: 0']
        c_ij[i] = {}
        for j in J:
            if j not in row:
                raise ValueError(f'Missing transportation cost for supplier {i}, customer {j}')
            try:
                c_ij[i][j] = float(row[j])
            except Exception:
                raise ValueError(f'Non-numeric transportation cost for supplier {i}, customer {j}: {row[j]}')
    if set(I) != set(c_ij.keys()):
        raise ValueError('Mismatch between supplier set and transportation cost rows')
    for i in I:
        if set(J) != set(c_ij[i].keys()):
            raise ValueError(f'Mismatch between customer set and transportation cost columns for supplier {i}')
    m = gp.Model('FLP')
    m.Params.MIPGap = 0.0001
    quantity_keys = [(i, j) for i in I for j in J]
    quantity_vars = m.addVars(quantity_keys, lb=0, vtype=GRB.CONTINUOUS, name='')
    activation_vars = m.addVars(I, vtype=GRB.BINARY, name='')
    m.setObjective(gp.quicksum((c_ij[i][j] * quantity_vars[i, j] for i in I for j in J)) + gp.quicksum((f_i[i] * activation_vars[i] for i in I)), GRB.MINIMIZE)
    m.addConstrs((gp.quicksum((quantity_vars[i, j] for i in I)) == d_j[j] for j in J), name='')
    m.optimize()
    return m
m = solve_problem(CSVQA_FRAMES)
if m.Status == GRB.OPTIMAL:
    print(f'ObjVal: {m.ObjVal}')
