import pandas as pd
CSVQA_FRAMES = {t["table_id"]: pd.DataFrame([r["values"] for r in t["records"]], columns=t["columns"], index=[r["source_row"] for r in t["records"]]) for t in CSVQA_DATA["tables"]}
import gurobipy as gp
from gurobipy import GRB

def solve_problem(CSVQA_FRAMES):
    df_warehouses = CSVQA_FRAMES['file_0_view_0']
    df_stores = CSVQA_FRAMES['file_1_view_0']
    df_cost = CSVQA_FRAMES['file_2_view_0']
    warehouses = [row['Warehouse (i)'] for row in df_warehouses.to_dict('records')]
    opening_cost = {}
    capacity = {}
    for row in df_warehouses.to_dict('records'):
        i = row['Warehouse (i)']
        try:
            opening_cost[i] = float(row['Opening Cost (fi)'])
        except Exception:
            raise ValueError(f'Missing or invalid Opening Cost (fi) for warehouse {i}')
        try:
            capacity[i] = float(row['Capacity (units)'])
        except Exception:
            raise ValueError(f'Missing or invalid Capacity (units) for warehouse {i}')
    stores = [row['Store (j)'] for row in df_stores.to_dict('records')]
    demand = {}
    for row in df_stores.to_dict('records'):
        j = row['Store (j)']
        try:
            demand[j] = float(row['Demand (units, dj)'])
        except Exception:
            raise ValueError(f'Missing or invalid Demand (units, dj) for store {j}')
    cost = {}
    for row in df_cost.to_dict('records'):
        row_warehouse = row['Unnamed: 3']
        if not row_warehouse or not row_warehouse.startswith('W'):
            continue
        i = row_warehouse[1:]
        if i not in warehouses:
            continue
        cost[i] = {}
        for j in stores:
            col = 'W' + j
            if col not in row:
                raise ValueError(f'Missing transportation cost column {col} for store {j}')
            try:
                cost[i][j] = float(row[col])
            except Exception:
                raise ValueError(f'Missing or invalid transportation cost for warehouse {i}, store {j}')
    for i in warehouses:
        if i not in cost:
            raise ValueError(f'Missing cost row for warehouse {i}')
        for j in stores:
            if j not in cost[i]:
                raise ValueError(f'Missing cost for warehouse {i}, store {j}')
    m = gp.Model('FLP')
    quantity_vars = m.addVars(warehouses, stores, lb=0, vtype=GRB.CONTINUOUS, name='')
    open_vars = m.addVars(warehouses, vtype=GRB.BINARY, name='')
    m.setObjective(gp.quicksum((cost[i][j] * quantity_vars[i, j] for i in warehouses for j in stores)) + gp.quicksum((opening_cost[i] * open_vars[i] for i in warehouses)), GRB.MINIMIZE)
    m.addConstrs((gp.quicksum((quantity_vars[i, j] for i in warehouses)) == demand[j] for j in stores), name='')
    m.addConstrs((gp.quicksum((quantity_vars[i, j] for j in stores)) <= capacity[i] * open_vars[i] for i in warehouses), name='')
    m.Params.MIPGap = 0.0001
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for var in m.getVars():
            print(f'{var.VarName}: {var.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem(CSVQA_FRAMES)