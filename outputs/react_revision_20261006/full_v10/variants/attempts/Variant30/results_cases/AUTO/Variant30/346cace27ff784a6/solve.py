    w_vars = m.addVars(B, vtype=gp.GRB.BINARY, name='')
    obj = gp.quicksum((benefit_i[i] * x_vars[i] for i in I))
    obj -= gp.quicksum((item_fee_i[i] * y_vars[i] for i in I))
    obj -= gp.quicksum((cat_fee_c[c] * z_vars[c] for c in C))
    obj += gp.quicksum((bundle_bonus[i, j] * w_vars[i, j] for (i, j) in B))
    m.setObjective(obj, gp.GRB.MAXIMIZE)
    for i in I:
        if authorized_i[i] == 0:
            m.addConstr(x_vars[i] == 0, name=f'unauth_{i}')
            m.addConstr(y_vars[i] == 0, name=f'unauth_y_{i}')
        else:
            m.addConstr(min_lot_i[i] * y_vars[i] <= x_vars[i], name=f'minlot_{i}')
            m.addConstr(x_vars[i] <= max_order_i[i] * y_vars[i], name=f'maxorder_{i}')
    for c in C:
        items_in_c = [i for i in I if cat_i[i] == c]
        for i in items_in_c:
            m.addConstr(z_vars[c] >= y_vars[i], name=f'catact_{c}_{i}')
        m.addConstr(min_cat_c[c] * z_vars[c] <= gp.quicksum((x_vars[i] for i in items_in_c)), name=f'mincat_{c}')
        m.addConstr(gp.quicksum((x_vars[i] for i in items_in_c)) <= max_cat_c[c] * z_vars[c], name=f'maxcat_{c}')
    for r in R:
        m.addConstr(gp.quicksum((usage_ir_conv[i, r] * x_vars[i] for i in I)) <= cap_r[r], name=f'cap_{r}')
    for (i, j) in P:
        if i in I and j in I:
            m.addConstr(y_vars[i] + y_vars[j] <= 1, name=f'incompat_{i}_{j}')
    for (i, j) in Q:
        if i in I and j in I:
            m.addConstr(y_vars[i] <= y_vars[j], name=f'requires_{i}_{j}')
    for (i, j) in B:
        if i in I and j in I:
            m.addConstr(w_vars[i, j] <= y_vars[i], name=f'bundle1_{i}_{j}')
            m.addConstr(w_vars[i, j] <= y_vars[j], name=f'bundle2_{i}_{j}')
            m.addConstr(w_vars[i, j] >= y_vars[i] + y_vars[j] - 1, name=f'bundle3_{i}_{j}')
        else:
            m.addConstr(w_vars[i, j] == 0, name=f'bundle_ineligible_{i}_{j}')
    m.Params.MIPGap = 0.0001
    m.optimize()
    return m
