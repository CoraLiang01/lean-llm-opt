import pandas as pd
CSVQA_FRAMES = {t["table_id"]: pd.DataFrame([r["values"] for r in t["records"]], columns=t["columns"], index=[r["source_row"] for r in t["records"]]) for t in CSVQA_DATA["tables"]}
import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    cost_frame = CSVQA_FRAMES['file_0_view_0']
    demand_frame = CSVQA_FRAMES['file_1_view_0']
    plants = []
    fixed_opening_cost = {}
    facility_capacity = {}
    transportation_cost = {}
    for (_, row) in cost_frame.iterrows():
        plant = row['facility_id']
        plants.append(plant)
        fixed_opening_cost[plant] = float(row['fixed_opening_cost'])
        facility_capacity[plant] = float(row['facility_capacity'])
        transportation_cost[plant] = {}
        for j in range(1, 16):
            customer = f'C{j}'
            col = f'transportation_cost_to_{customer}'
            transportation_cost[plant][customer] = float(row[col])
    customers = []
    demand_units = {}
    for (_, row) in demand_frame.iterrows():
        customer = row['customer_id']
        customers.append(customer)
        demand_units[customer] = float(row['demand_units'])
    if len(plants) != 15 or len(customers) != 15:
        raise ValueError('Expected 15 plants and 15 customers.')
    for plant in plants:
        if plant not in fixed_opening_cost or plant not in facility_capacity or plant not in transportation_cost:
            raise ValueError(f'Missing data for plant {plant}.')
        for customer in customers:
            if customer not in transportation_cost[plant]:
                raise ValueError(f'Missing transportation cost for plant {plant}, customer {customer}.')
    for customer in customers:
        if customer not in demand_units:
            raise ValueError(f'Missing demand for customer {customer}.')
    m = gp.Model('Facility_Location')
    m.setParam('MIPGap', 0.0001)
    x_vars = m.addVars(plants, customers, lb=0, vtype=GRB.CONTINUOUS, name='')
    y_vars = m.addVars(plants, vtype=GRB.BINARY, name='')
    m.setObjective(gp.quicksum((transportation_cost[i][j] * x_vars[i, j] for i in plants for j in customers)) + gp.quicksum((fixed_opening_cost[i] * y_vars[i] for i in plants)), GRB.MINIMIZE)
    m.addConstrs((gp.quicksum((x_vars[i, j] for i in plants)) == demand_units[j] for j in customers), name='')
    m.addConstrs((gp.quicksum((x_vars[i, j] for j in customers)) <= facility_capacity[i] * y_vars[i] for i in plants), name='')
    m.optimize()
    return m
m = solve_problem()