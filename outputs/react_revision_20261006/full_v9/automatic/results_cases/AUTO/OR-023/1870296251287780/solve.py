import pandas as pd
CSVQA_FRAMES = {t["table_id"]: pd.DataFrame([r["values"] for r in t["records"]], columns=t["columns"], index=[r["source_row"] for r in t["records"]]) for t in CSVQA_DATA["tables"]}
import gurobipy as gp
from gurobipy import GRB

def solve_problem(CSVQA_FRAMES):
    import pandas as pd
    frame = CSVQA_FRAMES['file_0_view_0']
    mask = frame['Product_Reference'].str.casefold().str.startswith('ele-s')
    filtered = frame[mask]
    I = []
    revenue = {}
    demand = {}
    inventory = {}
    for (source_row, row) in filtered.iterrows():
        prod_ref = row['Product_Reference']
        try:
            A_i = float(row['Revenue'])
            d_i = float(row['Demand'])
            I_i = float(row['Initial Inventory'])
        except Exception as e:
            raise ValueError(f'Non-numeric value in row {source_row} for product {prod_ref}: {e}')
        I.append(prod_ref)
        revenue[prod_ref] = A_i
        demand[prod_ref] = d_i
        inventory[prod_ref] = I_i
    if not I:
        raise ValueError("No products found with Product_Reference starting with 'ELE-S'.")
    m = gp.Model('ELE-S_Revenue_Maximization')
    quantity_vars = m.addVars(I, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((revenue[i] * quantity_vars[i] for i in I)), GRB.MAXIMIZE)
    m.addConstrs((quantity_vars[i] <= inventory[i] for i in I), name='')
    m.addConstrs((quantity_vars[i] <= demand[i] for i in I), name='')
    m.setParam('MIPGap', 0.0001)
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for var in m.getVars():
            print(f'{var.VarName}: {var.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem(CSVQA_FRAMES)