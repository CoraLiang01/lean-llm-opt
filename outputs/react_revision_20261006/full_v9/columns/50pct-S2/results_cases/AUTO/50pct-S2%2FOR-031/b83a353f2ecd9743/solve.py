import pandas as pd

def solve_problem(CSVQA_FRAMES):
    frame = CSVQA_FRAMES['file_0_view_0']
    I = []
    g = {}
    c = {}
    for (source_row, row) in frame.iterrows():
        option = row['option']
        if option in I:
            raise ValueError(f'Duplicate option identifier: {option}')
        I.append(option)
        try:
            g[option] = float(row['gen_per_lot'])
        except Exception:
            raise ValueError(f"Invalid gen_per_lot for option {option}: {row['gen_per_lot']}")
        try:
            c[option] = float(row['cost_per_lot'])
        except Exception:
            raise ValueError(f"Invalid cost_per_lot for option {option}: {row['cost_per_lot']}")
    if len(I) == 0:
        raise ValueError('No generation options found in energy.csv')
    D = 200.0
    m = gp.Model('Electricity_Generation_Lot_Purchase')
    x_vars = m.addVars(I, vtype=gp.GRB.INTEGER, lb=0, name='')
    m.setObjective(gp.quicksum((c[i] * x_vars[i] for i in I)), gp.GRB.MINIMIZE)
    m.addConstr(gp.quicksum((g[i] * x_vars[i] for i in I)) >= D, name='Demand')
    m.Params.MIPGap = 0.0001
    m.optimize()
    return m
