import pandas as pd
CSVQA_FRAMES = {t["table_id"]: pd.DataFrame([r["values"] for r in t["records"]], columns=t["columns"], index=[r["source_row"] for r in t["records"]]) for t in CSVQA_DATA["tables"]}
import gurobipy as gp
import pandas as pd
import numpy as np

def solve_problem(CSVQA_FRAMES):
    bundle_frame = CSVQA_FRAMES['file_0_view_0']
    B = []
    bonus = {}
    for (_, row) in bundle_frame.iterrows():
        i = row['item_a']
        j = row['item_b']
        B.append((i, j))
        bonus[i, j] = float(row['bonus_cents'])
    cap_frame = CSVQA_FRAMES['file_1_view_0']
    cap = {}
    for (_, row) in cap_frame.iterrows():
        resource = row['resource']
        amount = float(row['amount'])
        cap[resource] = cap.get(resource, 0.0) + amount
    L = list(cap.keys())
    cat_frame = CSVQA_FRAMES['file_2_view_0']
    C = []
    catmin = {}
    catmax = {}
    catfee = {}
    for (_, row) in cat_frame.iterrows():
        c = row['category']
        C.append(c)
        catmin[c] = float(row['minimum_quantity'])
        catmax[c] = float(row['maximum_quantity'])
        catfee[c] = float(row['activation_fee_cents'])
    inc_frame = CSVQA_FRAMES['file_4_view_0']
    INC = []
    for (_, row) in inc_frame.iterrows():
        i = row['item_a']
        j = row['item_b']
        INC.append((i, j))
    item_frames = [CSVQA_FRAMES['file_5_view_0'], CSVQA_FRAMES['file_6_view_0']]
    I = []
    I_auth = []
    unit_benefit = {}
    item_fee = {}
    cat_of = {}
    loc_of = {}
    minlot = {}
    maxord = {}
    auth = {}
    for frame in item_frames:
        for (_, row) in frame.iterrows():
            i = row['item_ref']
            I.append(i)
            authorized = int(row['authorized'])
            auth[i] = authorized
            if authorized == 1:
                I_auth.append(i)
            unit_benefit[i] = float(row['unit_benefit_cents'])
            item_fee[i] = float(row['item_fee_cents'])
            cat_of[i] = row['category']
            loc_of[i] = row['location_id']
            minlot[i] = float(row['minimum_lot'])
            maxord[i] = float(row['maximum_order'])
    req_frame = CSVQA_FRAMES['file_8_view_0']
    REQ = []
    for (_, row) in req_frame.iterrows():
        i = row['item_ref']
        prereq = row['prerequisite_ref']
        REQ.append((i, prereq))
    usage = {}
    usage_frames = [CSVQA_FRAMES['file_9_view_0'], CSVQA_FRAMES['file_10_view_0']]
    for frame in usage_frames:
        for (_, row) in frame.iterrows():
            i = row['item_ref']
            l = row['resource']
            amt = float(row['amount'])
            usage[i, l] = usage.get((i, l), 0.0) + amt
    for (i, l) in usage:
        if l not in L:
            L.append(l)
    m = gp.Model('FC_EAST_HVAC_AC_Placement')
    m.Params.MIPGap = 0.0001
    x_vars = {}
    for i in I:
        if auth[i] == 1:
            x_vars[i] = m.addVar(vtype=gp.GRB.INTEGER, lb=0, ub=maxord[i], name=f'x_{i}')
        else:
            x_vars[i] = m.addVar(vtype=gp.GRB.INTEGER, lb=0, ub=0, name=f'x_{i}')
    y_vars = {}
    for i in I:
        y_vars[i] = m.addVar(vtype=gp.GRB.BINARY, name=f'y_{i}')
    z_vars = {}
    for c in C:
        z_vars[c] = m.addVar(vtype=gp.GRB.BINARY, name=f'z_{c}')
    w_vars = {}
    for (i, j) in B:
        w_vars[i, j] = m.addVar(vtype=gp.GRB.BINARY, name=f'w_{i}_{j}')
    m.update()
    for i in I:
        if auth[i] == 1:
            m.addConstr(x_vars[i] >= minlot[i] * y_vars[i], name=f'x_minlot_{i}')
            m.addConstr(x_vars[i] <= maxord[i] * y_vars[i], name=f'x_maxord_{i}')
        else:
            m.addConstr(x_vars[i] == 0, name=f'x_zero_unauth_{i}')
            m.addConstr(y_vars[i] == 0, name=f'y_zero_unauth_{i}')
    for l in L:
        m.addConstr(gp.quicksum((usage.get((i, l), 0.0) * x_vars[i] for i in I)) <= cap.get(l, 0.0), name=f'cap_{l}')
    for c in C:
        m.addConstr(gp.quicksum((x_vars[i] for i in I if cat_of[i] == c)) >= catmin[c], name=f'catmin_{c}')
        m.addConstr(gp.quicksum((x_vars[i] for i in I if cat_of[i] == c)) <= catmax[c], name=f'catmax_{c}')
        for i in I:
            if cat_of[i] == c:
                m.addConstr(z_vars[c] >= y_vars[i], name=f'zcat_{c}_{i}')
    for (i, j) in INC:
        m.addConstr(y_vars[i] + y_vars[j] <= 1, name=f'incomp_{i}_{j}')
    for (i, prereq) in REQ:
        m.addConstr(y_vars[i] <= y_vars[prereq], name=f'req_{i}_{prereq}')
    for (i, j) in B:
        m.addConstr(w_vars[i, j] <= y_vars[i], name=f'wleqyi_{i}_{j}')
        m.addConstr(w_vars[i, j] <= y_vars[j], name=f'wleqyj_{i}_{j}')
        m.addConstr(w_vars[i, j] >= y_vars[i] + y_vars[j] - 1, name=f'wgeqsum_{i}_{j}')
    obj = gp.LinExpr()
    obj += gp.quicksum((unit_benefit[i] * x_vars[i] - item_fee[i] * y_vars[i] for i in I if auth[i] == 1))
    obj += -gp.quicksum((catfee[c] * z_vars[c] for c in C))
    obj += gp.quicksum((bonus[i, j] * w_vars[i, j] for (i, j) in B))
    m.setObjective(obj, gp.GRB.MAXIMIZE)
    m.update()
    m.optimize()
    return m
m = solve_problem(CSVQA_FRAMES)