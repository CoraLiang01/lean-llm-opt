import pandas as pd
CSVQA_FRAMES = {t["table_id"]: pd.DataFrame([r["values"] for r in t["records"]], columns=t["columns"], index=[r["source_row"] for r in t["records"]]) for t in CSVQA_DATA["tables"]}
import gurobipy as gp
from gurobipy import GRB

def solve_problem(CSVQA_FRAMES):
    warehouse_frame = CSVQA_FRAMES['file_1_view_0']
    I = []
    f_i = {}
    cap_i = {}
    for (_, row) in warehouse_frame.iterrows():
        wid = row['Warehouse ID']
        I.append(wid)
        try:
            f_i[wid] = float(row['Fixed_Cost'])
        except Exception:
            raise ValueError(f'Invalid Fixed_Cost for warehouse {wid}')
        try:
            cap_i[wid] = float(row['Capacity'])
        except Exception:
            raise ValueError(f'Invalid Capacity for warehouse {wid}')
    customer_frame = CSVQA_FRAMES['file_2_view_0']
    J = []
    d_j = {}
    for (_, row) in customer_frame.iterrows():
        cid = row['Customer ID']
        J.append(cid)
        try:
            d_j[cid] = float(row['Demand'])
        except Exception:
            raise ValueError(f'Invalid Demand for customer {cid}')
    cost_frame = CSVQA_FRAMES['file_0_view_0']
    c_ij = {}
    for (_, row) in cost_frame.iterrows():
        wid = row['Warehouse ID']
        if wid not in I:
            raise ValueError(f'Warehouse {wid} in cost matrix not found in warehouse list')
        for cid in J:
            if cid not in row:
                raise ValueError(f'Customer {cid} not found as column in cost matrix')
            try:
                c_ij[wid, cid] = float(row[cid])
            except Exception:
                raise ValueError(f'Invalid cost for warehouse {wid}, customer {cid}')
    for wid in I:
        for cid in J:
            if (wid, cid) not in c_ij:
                raise ValueError(f'Missing cost coefficient for warehouse {wid}, customer {cid}')
    for wid in I:
        if wid not in f_i or wid not in cap_i:
            raise ValueError(f'Missing fixed cost or capacity for warehouse {wid}')
    for cid in J:
        if cid not in d_j:
            raise ValueError(f'Missing demand for customer {cid}')
    m = gp.Model('FLP')
    m.setParam('MIPGap', 0.0001)
    quantity_vars = m.addVars(I, J, lb=0, vtype=GRB.CONTINUOUS, name='')
    open_vars = m.addVars(I, vtype=GRB.BINARY, name='')
    m.setObjective(gp.quicksum((c_ij[i, j] * quantity_vars[i, j] for i in I for j in J)) + gp.quicksum((f_i[i] * open_vars[i] for i in I)), GRB.MINIMIZE)
    m.addConstrs((gp.quicksum((quantity_vars[i, j] for i in I)) == d_j[j] for j in J), name='')
    m.addConstrs((gp.quicksum((quantity_vars[i, j] for j in J)) <= cap_i[i] * open_vars[i] for i in I), name='')
    m.optimize()
    return m
m = solve_problem(CSVQA_FRAMES)
if m.Status == GRB.OPTIMAL:
    print(f'ObjVal: {m.ObjVal}')
    for var in m.getVars():
        print(f'{var.VarName}: {var.X}')
else:
    print(f'Solver status: {m.Status}')