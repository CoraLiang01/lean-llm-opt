import pandas as pd
CSVQA_FRAMES = {t["table_id"]: pd.DataFrame([r["values"] for r in t["records"]], columns=t["columns"], index=[r["source_row"] for r in t["records"]]) for t in CSVQA_DATA["tables"]}
import gurobipy as gp
import pandas as pd
import numpy as np
import sys

def solve_tsp():
    frame = CSVQA_FRAMES['file_0_view_0']
    n_locations = 15
    N = list(range(1, n_locations + 1))
    d = {}
    for i in N:
        for j in N:
            if i != j:
                d[i, j] = None
    for (source_row, row) in frame.iterrows():
        i = source_row + 1
        for col in frame.columns:
            j = int(col)
            if i < j:
                val = row[col]
                if val == '' or val is None:
                    raise ValueError(f'Missing distance for ({i},{j}) in CSV.')
                d[i, j] = float(val)
                d[j, i] = float(val)
    for i in N:
        for j in N:
            if i != j and d[i, j] is None:
                raise ValueError(f'Distance missing for ({i},{j})')
    m = gp.Model('TSP15')
    m.Params.MIPGap = 0.0001
    x_keys = [(i, j) for i in N for j in N if i != j]
    x_vars = m.addVars(x_keys, vtype=gp.GRB.BINARY, name='')
    u_keys = [i for i in N if i != 1]
    u_vars = m.addVars(u_keys, lb=2, ub=15, vtype=gp.GRB.CONTINUOUS, name='')
    m.setObjective(gp.quicksum((d[i, j] * x_vars[i, j] for (i, j) in x_keys)), gp.GRB.MINIMIZE)
    for i in N:
        m.addConstr(gp.quicksum((x_vars[i, j] for j in N if j != i)) == 1, name='leave_%d' % i)
    for j in N:
        m.addConstr(gp.quicksum((x_vars[i, j] for i in N if i != j)) == 1, name='enter_%d' % j)
    for i in N:
        if i == 1:
            continue
        for j in N:
            if j == 1 or i == j:
                continue
            m.addConstr(u_vars[i] - u_vars[j] + 15 * x_vars[i, j] <= 14, name='mtz_%d_%d' % (i, j))
    m.optimize()
    return m
m = solve_tsp()