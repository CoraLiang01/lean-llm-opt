import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    data = CSVQA_DATA
    supply_table = next((t for t in data['tables'] if t['table_id'] == 'file_1_view_0'))
    suppliers = [rec['values']['supplier_id'] for rec in supply_table['records']]
    supply_capacity = {}
    for rec in supply_table['records']:
        sid = rec['values']['supplier_id']
        sval = rec['values']['supply_capacity_units']
        supply_capacity[sid] = float(sval)
    demand_table = next((t for t in data['tables'] if t['table_id'] == 'file_0_view_0'))
    customers = [rec['values']['customer_id'] for rec in demand_table['records']]
    demand = {}
    for rec in demand_table['records']:
        cid = rec['values']['customer_id']
        dval = rec['values']['demand_units']
        demand[cid] = float(dval)
    cost_table = next((t for t in data['tables'] if t['table_id'] == 'file_2_view_0'))
    rel = next((r for r in data['relationships'] if r['matrix_table_id'] == 'file_2_view_0'))
    col_map = rel['column_id_mapping']
    cost = {}
    for rec in cost_table['records']:
        sid = rec['values']['supplier_id']
        cost[sid] = {}
        for (col, cid) in col_map.items():
            cval = rec['values'][col]
            cost[sid][cid] = float(cval)
    if set(suppliers) != set(cost.keys()):
        raise ValueError('Mismatch between suppliers in supply_capacity and cost matrix')
    for sid in suppliers:
        if set(customers) != set(cost[sid].keys()):
            raise ValueError(f'Mismatch between customers in cost matrix for supplier {sid}')
    if set(customers) != set(demand.keys()):
        raise ValueError('Mismatch between customers in demand and cost matrix')
    if set(suppliers) != set(supply_capacity.keys()):
        raise ValueError('Mismatch between suppliers in supply_capacity and cost matrix')
    m = gp.Model('Original_RAG_TP')
    x_keys = [(i, j) for i in suppliers for j in customers]
    x = m.addVars(x_keys, lb=0, vtype=GRB.CONTINUOUS, name='')
    m.setObjective(gp.quicksum((cost[i][j] * x[i, j] for i in suppliers for j in customers)), GRB.MINIMIZE)
    m.addConstrs((gp.quicksum((x[i, j] for i in suppliers)) >= demand[j] for j in customers), name='')
    m.addConstrs((gp.quicksum((x[i, j] for j in customers)) <= supply_capacity[i] for i in suppliers), name='')
    m.Params.MIPGap = 0.0001
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for var in m.getVars():
            print(f'{var.VarName}: {var.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()