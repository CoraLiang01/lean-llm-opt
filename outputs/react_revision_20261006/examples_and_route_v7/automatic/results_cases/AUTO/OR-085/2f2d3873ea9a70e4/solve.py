import pandas as pd
CSVQA_FRAMES = {t["table_id"]: pd.DataFrame([r["values"] for r in t["records"]], columns=t["columns"], index=[r["source_row"] for r in t["records"]]) for t in CSVQA_DATA["tables"]}
import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    import pandas as pd
    table_id = 'file_0_view_0'
    df = CSVQA_FRAMES[table_id]
    n = 15
    locations = list(range(1, n + 1))
    d = {}
    for i in locations:
        d[i] = {}
        for j in locations:
            d[i][j] = None
    for (row_idx, row) in enumerate(df.itertuples(index=False)):
        i = row_idx + 1
        for col_name in df.columns:
            j = int(col_name)
            val = getattr(row, col_name)
            if val != '':
                d[i][j] = float(val)
                d[j][i] = float(val)
    for i in locations:
        d[i][i] = 0.0
    for i in locations:
        for j in locations:
            if i != j and d[i][j] is None:
                raise ValueError(f'Missing distance from {i} to {j}')
    m = gp.Model('TSP_15_MTZ')
    x_keys = [(i, j) for i in locations for j in locations if i != j]
    x_vars = m.addVars(x_keys, vtype=GRB.BINARY, name='')
    u_vars = m.addVars(locations, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((d[i][j] * x_vars[i, j] for (i, j) in x_keys)), GRB.MINIMIZE)
    m.addConstrs((gp.quicksum((x_vars[i, j] for j in locations if j != i)) == 1 for i in locations), name='')
    m.addConstrs((gp.quicksum((x_vars[i, j] for i in locations if i != j)) == 1 for j in locations), name='')
    m.addConstr(u_vars[1] == 1, name='u1')
    for i in range(2, n + 1):
        m.addConstr(u_vars[i] >= 2, name=f'u_lb_{i}')
        m.addConstr(u_vars[i] <= n, name=f'u_ub_{i}')
    for i in range(2, n + 1):
        for j in range(2, n + 1):
            if i != j:
                m.addConstr(u_vars[i] - u_vars[j] + n * x_vars[i, j] <= n - 1, name=f'mtz_{i}_{j}')
    m.Params.MIPGap = 0.0001
    m.optimize()
    return m
m = solve_problem()