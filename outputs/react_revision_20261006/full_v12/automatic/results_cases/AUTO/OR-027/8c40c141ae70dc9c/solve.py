import pandas as pd
CSVQA_FRAMES = {t["table_id"]: pd.DataFrame([r["values"] for r in t["records"]], columns=t["columns"], index=[r["source_row"] for r in t["records"]]) for t in CSVQA_DATA["tables"]}
import gurobipy as gp
from gurobipy import GRB

def solve_problem(CSVQA_FRAMES):
    frame = CSVQA_FRAMES['file_0_view_0']
    mask = frame['Sub Category'].str.casefold().str.contains('organ')
    organ_frame = frame[mask]
    items = []
    revenue = {}
    demand = {}
    inventory = {}
    for (source_row, row) in organ_frame.iterrows():
        identifier = row['Sub Category']
        try:
            A_i = float(row['Revenue'])
            d_i = float(row['Demand'])
            s_i = float(row['Initial Inventory'])
        except Exception as e:
            raise ValueError(f"Non-numeric value in row {source_row} for product '{identifier}': {e}")
        items.append(identifier)
        revenue[identifier] = A_i
        demand[identifier] = d_i
        inventory[identifier] = s_i
    if not items:
        raise ValueError("No products with 'Organ' in 'Sub Category' found.")
    if set(revenue) != set(items) or set(demand) != set(items) or set(inventory) != set(items):
        raise ValueError('Missing parameter data for some products.')
    m = gp.Model('Supermart_Organ_Revenue')
    m.setParam('MIPGap', 0.0001)
    quantity_vars = m.addVars(items, vtype=GRB.INTEGER, lb=0, name='')
    m.setObjective(gp.quicksum((revenue[i] * quantity_vars[i] for i in items)), GRB.MAXIMIZE)
    m.addConstrs((quantity_vars[i] <= demand[i] for i in items), name='')
    m.addConstrs((quantity_vars[i] <= inventory[i] for i in items), name='')
    m.optimize()
    return m
m = solve_problem(CSVQA_FRAMES)