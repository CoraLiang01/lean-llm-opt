CSVQA_FRAMES = {t["table_id"]: pd.DataFrame([r["values"] for r in t["records"]], columns=t["columns"], index=[r["source_row"] for r in t["records"]]) for t in CSVQA_DATA["tables"]}
import gurobipy as gp
import pandas as pd
import numpy as np

def solve_problem(CSVQA_FRAMES):
    items_df = CSVQA_FRAMES['file_7_view_0']
    I = []
    item_cat = {}
    item_loc = {}
    min_i = {}
    max_i = {}
    authorized_items = set()
    unauthorized_items = set()
    for (idx, row) in items_df.iterrows():
        item = row['item_ref']
        if row['authorized'] == '1':
            I.append(item)
            authorized_items.add(item)
            item_cat[item] = row['category']
            item_loc[item] = row['location_id']
            min_i[item] = int(row['minimum_lot'])
            max_i[item] = int(row['maximum_order'])
        else:
            unauthorized_items.add(item)
    I = list(I)
    categories_df = CSVQA_FRAMES['file_3_view_0']
    C = []
    F_c = {}
    min_c = {}
    max_c = {}
    for (idx, row) in categories_df.iterrows():
        c = row['category']
        C.append(c)
        F_c[c] = int(row['activation_fee_cents'])
        min_c[c] = int(row['minimum_quantity'])
        max_c[c] = int(row['maximum_quantity'])
    resources_df = CSVQA_FRAMES['file_2_view_0']
    L = []
    for (idx, row) in resources_df.iterrows():
        res = row['resource']
        if res not in L:
            L.append(res)
    bundles_df = CSVQA_FRAMES['file_1_view_0']
    B = []
    bonus_ab = {}
    for (idx, row) in bundles_df.iterrows():
        a = row['item_a']
        b = row['item_b']
        B.append((a, b))
        bonus_ab[a, b] = int(row['bonus_cents'])
    incompat_df = CSVQA_FRAMES['file_6_view_0']
    P = []
    for (idx, row) in incompat_df.iterrows():
        i = row['item_a']
        j = row['item_b']
        P.append((i, j))
    requires_df = CSVQA_FRAMES['file_10_view_0']
    Q = []
    for (idx, row) in requires_df.iterrows():
        i = row['item_ref']
        prereq = row['prerequisite_ref']
        Q.append((i, prereq))
    fx_df = CSVQA_FRAMES['file_4_view_0']
    fx = {}
    for (idx, row) in fx_df.iterrows():
        currency = row['currency']
        usd_cents_numerator = float(row['usd_cents_numerator'])
        denominator = float(row['denominator'])
        fx[currency] = usd_cents_numerator / denominator
    benefit_df = CSVQA_FRAMES['file_0_view_0']
    b_i = {i: 0.0 for i in I}
    for (idx, row) in benefit_df.iterrows():
        item = row['item_ref']
        if item in I:
            amount = float(row['amount'])
            currency = row['currency']
            if currency not in fx:
                raise ValueError(f'Missing FX for currency {currency}')
            b_i[item] += amount * fx[currency]
    item_fee_df = CSVQA_FRAMES['file_8_view_0']
    f_i = {}
    for (idx, row) in item_fee_df.iterrows():
        item = row['item_ref']
        if item in I:
            f_i[item] = int(row['activation_fee_cents'])
    for i in I:
        if i not in f_i:
            raise ValueError(f'Missing item fee for {i}')
    usage_df = CSVQA_FRAMES['file_11_view_0']
    u_iell = {(i, l): 0 for i in I for l in L}
    for (idx, row) in usage_df.iterrows():
        item = row['item_ref']
        res = row['resource']
        if item in I and res in L:
            amt = float(row['amount'])
            unit = row['unit']
            if unit.casefold() == 'gb':
                amt_mb = amt * 1000
            elif unit.casefold() == 'mb':
                amt_mb = amt
            else:
                raise ValueError(f'Unknown unit {unit}')
            u_iell[item, res] = amt_mb
    cap_ledger_df = CSVQA_FRAMES['file_2_view_0']
    cap_l = {l: 0.0 for l in L}
    for (idx, row) in cap_ledger_df.iterrows():
        res = row['resource']
        if res in L:
            amt = float(row['amount'])
            unit = row['unit']
            if unit.casefold() == 'gb':
                amt_mb = amt * 1000
            elif unit.casefold() == 'mb':
                amt_mb = amt
            else:
                raise ValueError(f'Unknown unit {unit}')
            cap_l[res] += amt_mb
    m = gp.Model('GameEditionAllocation')
    x_vars = {}
    for i in I:
        x_vars[i] = m.addVar(vtype=gp.GRB.INTEGER, lb=0, ub=max_i[i], name=f'x_{i}')
    y_vars = m.addVars(I, vtype=gp.GRB.BINARY, name='')
    z_vars = m.addVars(C, vtype=gp.GRB.BINARY, name='')
    w_vars = m.addVars(B, vtype=gp.GRB.BINARY, name='')
    for item in unauthorized_items:
        if item in x_vars:
            m.addConstr(x_vars[item] == 0, name=f'unauth_{item}')
    for i in I:
        m.addConstr(x_vars[i] >= min_i[i] * y_vars[i], name=f'minlot_{i}')
        m.addConstr(x_vars[i] <= max_i[i] * y_vars[i], name=f'maxorder_{i}')
    for c in C:
        items_in_c = [i for i in I if item_cat[i] == c]
        m.addConstr(gp.quicksum((x_vars[i] for i in items_in_c)) >= min_c[c], name=f'catmin_{c}')
        m.addConstr(gp.quicksum((x_vars[i] for i in items_in_c)) <= max_c[c], name=f'catmax_{c}')
        for i in items_in_c:
            m.addConstr(z_vars[c] >= y_vars[i], name=f'zcat_{c}_{i}')
    for l in L:
        items_in_l = [i for i in I if item_loc[i] == l]
        m.addConstr(gp.quicksum((u_iell[i, l] * x_vars[i] for i in items_in_l)) <= cap_l[l], name=f'mem_{l}')
    for (i, j) in P:
        if i in I and j in I:
            m.addConstr(y_vars[i] + y_vars[j] <= 1, name=f'incompat_{i}_{j}')
    for (i, prereq) in Q:
        if i in I and prereq in I:
            m.addConstr(y_vars[i] <= y_vars[prereq], name=f'requires_{i}_{prereq}')
    for (a, b) in B:
        if a in I and b in I:
            m.addConstr(w_vars[a, b] <= y_vars[a], name=f'wleya_{a}_{b}')
            m.addConstr(w_vars[a, b] <= y_vars[b], name=f'wleyb_{a}_{b}')
            m.addConstr(w_vars[a, b] >= y_vars[a] + y_vars[b] - 1, name=f'wgeya_yb_{a}_{b}')
        else:
            m.addConstr(w_vars[a, b] == 0, name=f'wzero_{a}_{b}')
    obj = gp.quicksum((b_i[i] * x_vars[i] - f_i[i] * y_vars[i] for i in I)) + gp.quicksum((-F_c[c] * z_vars[c] for c in C)) + gp.quicksum((bonus_ab[a, b] * w_vars[a, b] for (a, b) in B))
    m.setObjective(obj, gp.GRB.MAXIMIZE)
    m.Params.MIPGap = 0.0001
    m.optimize()
    return m
m = solve_problem(CSVQA_FRAMES)