import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    table = None
    for t in CSVQA_DATA['tables']:
        if t['table_id'] == 'file_0_view_0':
            table = t
            break
    if table is None:
        raise ValueError('Required table file_0_view_0 not found in CSVQA_DATA.')
    records = table['records']
    items = []
    revenue = {}
    demand = {}
    inventory = {}
    for rec in records:
        vals = rec['values']
        sku = vals['SKU']
        if not sku.casefold().startswith('zz'):
            continue
        items.append(sku)
        try:
            revenue[sku] = float(vals['Revenue'])
        except Exception:
            raise ValueError(f'Missing or invalid Revenue for SKU {sku}')
        try:
            demand[sku] = int(vals['Demand'])
        except Exception:
            raise ValueError(f'Missing or invalid Demand for SKU {sku}')
        try:
            inventory[sku] = float(vals['Initial Inventory'])
        except Exception:
            raise ValueError(f'Missing or invalid Initial Inventory for SKU {sku}')
    for sku in items:
        if sku not in revenue or sku not in demand or sku not in inventory:
            raise ValueError(f'Missing data for SKU {sku}')
    m = gp.Model('retail_store_zz_revenue')
    m.setParam('MIPGap', 0.0001)
    quantity_vars = m.addVars(items, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((revenue[i] * quantity_vars[i] for i in items)), GRB.MAXIMIZE)
    m.addConstrs((quantity_vars[i] <= demand[i] for i in items), name='')
    m.addConstrs((quantity_vars[i] <= inventory[i] for i in items), name='')
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for variable in m.getVars():
            print(f'{variable.VarName}: {variable.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()