import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    data = CSVQA_DATA
    supply_table = next((t for t in data['tables'] if t['table_id'] == 'file_1_view_0'))
    demand_table = next((t for t in data['tables'] if t['table_id'] == 'file_0_view_0'))
    cost_table = next((t for t in data['tables'] if t['table_id'] == 'file_2_view_0'))
    I = [rec['values']['Unnamed: 0'] for rec in supply_table['records']]
    J = [rec['values']['customer'] for rec in demand_table['records']]
    s_i = {}
    for rec in supply_table['records']:
        i = rec['values']['Unnamed: 0']
        s_i[i] = float(rec['values']['supply_capacity'])
    d_j = {}
    for rec in demand_table['records']:
        j = rec['values']['customer']
        d_j[j] = float(rec['values']['demand'])
    c_ij = {}
    for rec in cost_table['records']:
        i = rec['values']['Unnamed: 0']
        c_ij[i] = {}
        for j in J:
            c_ij[i][j] = float(rec['values'][j])
    for i in I:
        if i not in c_ij:
            raise ValueError(f'Missing cost row for distribution center {i}')
        for j in J:
            if j not in c_ij[i]:
                raise ValueError(f'Missing cost entry for ({i},{j})')
    for j in J:
        if j not in d_j:
            raise ValueError(f'Missing demand for customer group {j}')
    for i in I:
        if i not in s_i:
            raise ValueError(f'Missing supply capacity for distribution center {i}')
    m = gp.Model('Amazon_Distribution_Transportation')
    x = m.addVars(I, J, lb=0, vtype=GRB.CONTINUOUS, name='')
    m.setObjective(gp.quicksum((c_ij[i][j] * x[i, j] for i in I for j in J)), GRB.MINIMIZE)
    m.addConstrs((gp.quicksum((x[i, j] for i in I)) >= d_j[j] for j in J), name='')
    m.addConstrs((gp.quicksum((x[i, j] for j in J)) <= s_i[i] for i in I), name='')
    m.Params.MIPGap = 0.0001
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for var in m.getVars():
            print(f'{var.VarName}: {var.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()