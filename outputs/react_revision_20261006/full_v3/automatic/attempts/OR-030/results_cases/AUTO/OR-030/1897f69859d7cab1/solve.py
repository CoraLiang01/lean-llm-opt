import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    table = None
    for t in CSVQA_DATA['tables']:
        if t['table_id'] == 'file_0_view_0':
            table = t
            break
    if table is None:
        raise ValueError('Required table_id file_0_view_0 not found in CSVQA_DATA.')
    records = table['records']
    items = []
    revenue = {}
    demand = {}
    inventory = {}
    for rec in records:
        key = rec['source_row']
        vals = rec['values']
        for field in ['Revenue', 'Demand', 'Initial Inventory']:
            if field not in vals:
                raise ValueError(f'Missing field {field} in record {key}')
        try:
            A_i = float(vals['Revenue'])
            d_i = int(vals['Demand'])
            I_i = int(vals['Initial Inventory'])
        except Exception as e:
            raise ValueError(f'Invalid data in record {key}: {e}')
        items.append(key)
        revenue[key] = A_i
        demand[key] = d_i
        inventory[key] = I_i
    if not set(revenue.keys()) == set(demand.keys()) == set(inventory.keys()) == set(items):
        raise ValueError('Mismatch in index sets for revenue, demand, or inventory.')
    m = gp.Model('Car_Dealership_FDK57')
    m.setParam('MIPGap', 0.0001)
    x = m.addVars(items, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((revenue[i] * x[i] for i in items)), GRB.MAXIMIZE)
    m.addConstrs((x[i] <= demand[i] for i in items), name='')
    m.addConstrs((x[i] <= inventory[i] for i in items), name='')
    m.optimize()
    return m
m = solve_problem()
