import gurobipy as gp
from gurobipy import GRB

def solve_problem(CSVQA_DATA):
    table = None
    for t in CSVQA_DATA['tables']:
        if t['table_id'] == 'file_0_view_0':
            table = t
            break
    if table is None:
        raise RuntimeError("Required table_id 'file_0_view_0' not found in CSVQA_DATA.")
    I = []
    r = {}
    d = {}
    s = {}
    for rec in table['records']:
        pname = rec['values']['Product Name']
        if pname.startswith('27in'):
            I.append(pname)
            try:
                r[pname] = float(rec['values']['Revenue'])
                d[pname] = int(rec['values']['Demand'])
                s[pname] = int(rec['values']['Initial Inventory'])
            except Exception as e:
                raise RuntimeError(f"Error parsing data for product '{pname}': {e}")
    for i in I:
        if i not in r or i not in d or i not in s:
            raise RuntimeError(f"Missing data for product '{i}' in index set I.")
    m = gp.Model()
    m.Params.MIPGap = 0.0001
    x = m.addVars(I, vtype=GRB.INTEGER, lb=0, ub={i: min(d[i], s[i]) for i in I}, name='')
    m.setObjective(gp.quicksum((r[i] * x[i] for i in I)), GRB.MAXIMIZE)
    m.addConstrs((x[i] <= s[i] for i in I), name='')
    m.addConstrs((x[i] <= d[i] for i in I), name='')
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal {m.ObjVal}')
        for i in I:
            print(f'{x[i].VarName} {x[i].X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem(CSVQA_DATA)