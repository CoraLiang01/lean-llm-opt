import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    data_table = None
    for table in CSVQA_DATA['tables']:
        if table['table_id'] == 'file_0_view_0':
            data_table = table
            break
    if data_table is None:
        raise ValueError('Required table file_0_view_0 not found in CSVQA_DATA.')
    I = []
    r = {}
    d = {}
    s = {}
    for rec in data_table['records']:
        values = rec['values']
        product = values['Product Name']
        if not product.startswith('27in'):
            continue
        I.append(product)
        try:
            r[product] = float(values['Revenue'])
            d[product] = int(values['Demand'])
            s[product] = int(values['Initial Inventory'])
        except Exception as e:
            raise ValueError(f'Error parsing data for product {product}: {e}')
    for product in I:
        if product not in r or product not in d or product not in s:
            raise ValueError(f'Missing data for product {product}')
    m = gp.Model('27in_Product_Fulfillment')
    x = m.addVars(I, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((r[i] * x[i] for i in I)), GRB.MAXIMIZE)
    m.addConstrs((x[i] <= d[i] for i in I), name='')
    m.addConstrs((x[i] <= s[i] for i in I), name='')
    m.Params.MIPGap = 0.0001
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for var in m.getVars():
            print(f'{var.VarName}: {var.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()