import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    data = CSVQA_DATA
    platforms = []
    platform_capacity = {}
    for rec in [r['values'] for r in data['tables'][0]['records']]:
        pid = rec['resource_id']
        platforms.append(pid)
        platform_capacity[pid] = int(rec['resource_capacity'])
    genres = []
    genre_value = {}
    genre_requirement = {}
    for rec in [r['values'] for r in data['tables'][1]['records']]:
        jname = rec['item_name']
        genres.append(jname)
        genre_value[jname] = int(rec['item_value'])
        genre_requirement[jname] = int(rec['resource_requirement'])
    if len(platforms) == 0 or len(genres) == 0:
        raise ValueError('No platforms or genres found in data.')
    for pid in platforms:
        if pid not in platform_capacity:
            raise ValueError(f'Missing capacity for platform {pid}')
    for j in genres:
        if j not in genre_value or j not in genre_requirement:
            raise ValueError(f'Missing value or requirement for genre {j}')
    m = gp.Model('game_store_allocation')
    m.Params.MIPGap = 0.0001
    x = m.addVars(platforms, genres, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((genre_value[j] * x[i, j] for i in platforms for j in genres)), GRB.MAXIMIZE)
    m.addConstrs((gp.quicksum((genre_requirement[j] * x[i, j] for j in genres)) <= platform_capacity[i] for i in platforms), name='')
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for var in m.getVars():
            print(f'{var.VarName}: {var.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()