import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    displays = []
    c = {}
    for rec in CSVQA_DATA['tables'][0]['records']:
        shelf_id = rec['values']['ShelfID']
        displays.append(shelf_id)
        c[shelf_id] = float(rec['values']['Capacity'])
    products = []
    v = {}
    w = {}
    first_product = None
    for rec in CSVQA_DATA['tables'][1]['records']:
        pname = rec['values']['ProductName']
        products.append(pname)
        v[pname] = float(rec['values']['Value'])
        w[pname] = float(rec['values']['Weight'])
        if rec['source_row'] == 0:
            first_product = pname
    if first_product is None:
        raise ValueError('No product with source_row == 0 found for j*.')
    m = gp.Model('retail_display_allocation')
    x = m.addVars(displays, products, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((v[j] * x[i, j] for i in displays for j in products)), GRB.MAXIMIZE)
    m.addConstrs((gp.quicksum((w[j] * x[i, j] for j in products)) <= c[i] for i in displays), name='')
    m.addConstr(gp.quicksum((x[i, first_product] for i in displays)) >= 5, name='min_first_product')
    m.Params.MIPGap = 0.0001
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for var in m.getVars():
            print(f'{var.VarName}: {var.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()