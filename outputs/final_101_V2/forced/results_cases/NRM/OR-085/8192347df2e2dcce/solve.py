import gurobipy as gp
from gurobipy import GRB
import re
data = CSVQA_DATA
table = None
for t in data['tables']:
    if t['table_id'] == 'file_0_view_0':
        table = t
        break
if table is None:
    raise ValueError("Distance matrix table 'file_0_view_0' not found.")
n_nodes = 15
nodes = list(range(1, n_nodes + 1))
d = {}
for i, rec in enumerate(table['records']):
    i_node = i + 1
    d[i_node] = {}
    for j_str in table['columns']:
        j_node = int(j_str)
        if i_node == j_node:
            continue
        val = rec['values'][j_str]
        if val == '' or val is None:
            if j_node in d and i_node in d[j_node]:
                d[i_node][j_node] = d[j_node][i_node]
            else:
                raise ValueError(f'Missing distance for ({i_node},{j_node}) and symmetric entry not found.')
        else:
            if not re.fullmatch('\\d+', val):
                raise ValueError(f'Non-integer or malformed distance at ({i_node},{j_node}): {val}')
            d[i_node][j_node] = int(val)
for i in nodes:
    for j in nodes:
        if i == j:
            continue
        if j not in d[i]:
            raise ValueError(f'Distance missing for ({i},{j})')
        if i not in d[j]:
            raise ValueError(f'Distance missing for ({j},{i})')
        if d[i][j] != d[j][i]:
            raise ValueError(f'Distance matrix not symmetric at ({i},{j})')
m = gp.Model('TSP_MTZ')
x = m.addVars([(i, j) for i in nodes for j in nodes if i != j], vtype=GRB.BINARY, name='')
u = m.addVars([i for i in nodes if i != 1], lb=2, ub=n_nodes, vtype=GRB.INTEGER, name='')
m.setObjective(gp.quicksum((d[i][j] * x[i, j] for i in nodes for j in nodes if i != j)), GRB.MINIMIZE)
m.addConstrs((gp.quicksum((x[i, j] for j in nodes if j != i)) == 1 for i in nodes), name='')
m.addConstrs((gp.quicksum((x[i, j] for i in nodes if i != j)) == 1 for j in nodes), name='')
for i in nodes:
    if i == 1:
        continue
    for j in nodes:
        if j == 1 or i == j:
            continue
        m.addConstr(u[i] - u[j] + (n_nodes - 1) * x[i, j] <= n_nodes - 2, name=f'mtz_{i}_{j}')
u1 = m.addVar(lb=1, ub=1, vtype=GRB.INTEGER, name='u1')
m.addConstr(u1 == 1, name='u1_fix')
for j in nodes:
    if j == 1:
        continue
    m.addConstr(u[j] >= 2)
    m.addConstr(u[j] <= n_nodes)
m.Params.MIPGap = 0.0001
m.optimize()
if m.Status == GRB.OPTIMAL:
    print(f'ObjVal: {m.ObjVal}')
    for v in m.getVars():
        print(f'{v.VarName}: {v.X}')
else:
    print(f'Solver status: {m.Status}')