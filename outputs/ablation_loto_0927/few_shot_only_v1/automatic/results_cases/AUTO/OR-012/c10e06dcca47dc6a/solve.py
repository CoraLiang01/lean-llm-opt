columns = table['columns']
col_product = 'Product Name'
col_revenue = 'Revenue'
col_demand = 'Demand'
col_inventory = 'Initial Inventory'
num_re = re.compile('^\\s*(-?\\d+(?:\\.\\d+)?(?:[eE][-+]?\\d+)?)\\s*$')
products = []
revenue = {}
demand = {}
inventory = {}
for rec in records:
    vals = rec['values']
    if col_product not in vals:
        raise ValueError(f"Missing '{col_product}' in record.")
    prod = vals[col_product]
    products.append(prod)
    if col_revenue not in vals:
        raise ValueError(f"Missing '{col_revenue}' for product '{prod}'.")
    m = num_re.match(str(vals[col_revenue]))
    if not m:
        raise ValueError(f"Revenue value '{vals[col_revenue]}' for product '{prod}' is not a valid number.")
    revenue[prod] = float(m.group(1))
    if col_demand not in vals:
        raise ValueError(f"Missing '{col_demand}' for product '{prod}'.")
    m = num_re.match(str(vals[col_demand]))
    if not m:
        raise ValueError(f"Demand value '{vals[col_demand]}' for product '{prod}' is not a valid number.")
    demand[prod] = int(float(m.group(1)))
    if col_inventory not in vals:
        raise ValueError(f"Missing '{col_inventory}' for product '{prod}'.")
    m = num_re.match(str(vals[col_inventory]))
    if not m:
        raise ValueError(f"Initial Inventory value '{vals[col_inventory]}' for product '{prod}' is not a valid number.")
    inventory[prod] = int(float(m.group(1)))
if not set(products) == set(revenue) == set(demand) == set(inventory):
    raise ValueError('Mismatch in product indices among parameters.')
m = gp.Model('OnlineRetailerRevenueMax')
x = m.addVars(products, lb=0, ub={i: min(demand[i], inventory[i]) for i in products}, vtype=GRB.INTEGER, name='')
m.setObjective(gp.quicksum((revenue[i] * x[i] for i in products)), GRB.MAXIMIZE)
m.addConstrs((x[i] <= demand[i] for i in products), name='')
m.addConstrs((x[i] <= inventory[i] for i in products), name='')
m.Params.MIPGap = 0.0001
m.optimize()
if m.Status == GRB.OPTIMAL:
    print(f'ObjVal: {m.ObjVal}')
    for var in m.getVars():
        print(f'{var.VarName}: {var.X}')
else:
    print(f'Solver status: {m.Status}')