import gurobipy
from gurobipy import GRB
data = CSVQA_DATA

def solve_problem():
    table = next((t for t in data['tables'] if t['table_id'] == 'file_0_view_0'))
    records = table['records']
    I = []
    revenue = {}
    demand = {}
    inventory = {}
    for rec in records:
        values = rec['values']
        sku = values['SKU']
        try:
            rev = float(values['Revenue'])
            dem = int(values['Demand'])
            inv = float(values['Initial Inventory'])
        except (KeyError, ValueError) as e:
            raise ValueError(f'Missing or invalid data for SKU {sku}') from e
        if sku in I:
            revenue[sku] += rev
            demand[sku] += dem
            inventory[sku] += inv
        else:
            I.append(sku)
            revenue[sku] = rev
            demand[sku] = dem
            inventory[sku] = inv
    for i in I:
        if i not in revenue or i not in demand or i not in inventory:
            raise ValueError(f'Missing parameter for SKU {i}')
    m = gurobipy.Model()
    m.setParam('MIPGap', 1e-06)
    x = m.addVars(I, vtype=GRB.INTEGER, lb=0, name='')
    m.setObjective(gurobipy.quicksum((revenue[i] * x[i] for i in I)), GRB.MAXIMIZE)
    m.addConstrs((x[i] <= demand[i] for i in I), name='')
    m.addConstrs((x[i] <= inventory[i] for i in I), name='')
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(m.ObjVal)
        for var in m.getVars():
            print(var.VarName, var.X)
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()