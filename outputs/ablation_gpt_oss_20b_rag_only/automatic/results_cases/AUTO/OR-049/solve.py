import gurobipy as gp
from gurobipy import GRB
capacity_table = None
products_table = None
for tbl in CSVQA_DATA['tables']:
    if tbl['table_id'] == 'file_0_view_0':
        capacity_table = tbl
    elif tbl['table_id'] == 'file_1_view_0':
        products_table = tbl
if capacity_table is None or products_table is None:
    raise ValueError('Required tables not found in CSVQA_DATA')
S = set()
Cap = {}
for rec in capacity_table['records']:
    values = rec['values']
    shelf_id = values['ShelfID']
    if shelf_id in Cap:
        raise ValueError(f'Duplicate ShelfID {shelf_id}')
    try:
        cap_val = float(values['Capacity'])
    except ValueError:
        raise ValueError(f'Invalid capacity for ShelfID {shelf_id}')
    S.add(shelf_id)
    Cap[shelf_id] = cap_val
P = set()
Val = {}
Wgt = {}
for rec in products_table['records']:
    values = rec['values']
    prod_name = values['ProductName']
    if prod_name in Val:
        raise ValueError(f'Duplicate ProductName {prod_name}')
    try:
        val_val = float(values['Value'])
        wgt_val = float(values['Weight'])
    except ValueError:
        raise ValueError(f'Invalid value/weight for ProductName {prod_name}')
    P.add(prod_name)
    Val[prod_name] = val_val
    Wgt[prod_name] = wgt_val
for s in S:
    if s not in Cap:
        raise ValueError(f'Missing capacity for shelf {s}')
for p in P:
    if p not in Val or p not in Wgt:
        raise ValueError(f'Missing value or weight for product {p}')

def solve_problem():
    m = gp.Model()
    m.setParam('MIPGap', 1e-06)
    x = m.addVars([(s, p) for s in S for p in P], vtype=GRB.INTEGER, lb=0, name='')
    m.setObjective(gp.quicksum((Val[p] * x[s, p] for s in S for p in P)), GRB.MAXIMIZE)
    for s in S:
        m.addConstr(gp.quicksum((Wgt[p] * x[s, p] for p in P)) <= Cap[s])
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(m.ObjVal)
        for var in m.getVars():
            print(var.VarName, var.X)
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()