import gurobipy as gp
from gurobipy import GRB
table = CSVQA_DATA['tables'][0]['records']
N = len(table)
d = [[0] * N for _ in range(N)]
for r, rec in enumerate(table):
    node = r + 1
    for col, val in rec['values'].items():
        if val == '':
            continue
        j = int(col)
        dist = int(val)
        d[node - 1][j - 1] = dist
        d[j - 1][node - 1] = dist
m = gp.Model('TSP_MTZ')
x = {}
for i in range(N):
    for j in range(i + 1, N):
        x[i, j] = m.addVar(vtype=GRB.BINARY)
u = {}
for i in range(1, N):
    u[i] = m.addVar(vtype=GRB.CONTINUOUS, lb=2, ub=N - 1)
m.setObjective(gp.quicksum((d[i][j] * x[i, j] for i in range(N) for j in range(i + 1, N))), GRB.MINIMIZE)
for i in range(N):
    incident = gp.quicksum((x[min(i, j), max(i, j)] for j in range(N) if j != i))
    m.addConstr(incident == 2)
for i in range(1, N):
    for j in range(i + 1, N):
        m.addConstr(u[i] - u[j] + (N - 1) * x[i, j] <= N - 2)
m.Params.MIPGap = 1e-06
m.optimize()
if m.Status == GRB.OPTIMAL:
    print(f'ObjVal: {m.ObjVal}')
    for var in m.getVars():
        print(f'{var.VarName} = {var.X}')
else:
    print(f'Status: {m.Status}')