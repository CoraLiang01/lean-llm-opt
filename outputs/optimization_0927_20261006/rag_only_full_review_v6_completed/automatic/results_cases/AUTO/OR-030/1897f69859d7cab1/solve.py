from gurobipy import Model, GRB, quicksum

def build_and_solve():
    table = None
    for t in CSVQA_DATA['tables']:
        if t['table_id'] == 'file_0_view_0':
            table = t
            break
    if table is None:
        raise RuntimeError("Required table_id 'file_0_view_0' not found in CSVQA_DATA.")
    I = []
    r = {}
    s = {}
    d = {}
    for rec in table['records']:
        vals = rec['values']
        if vals['Product Name'] != 'FDK57':
            continue
        idx = rec['source_row']
        I.append(idx)
        try:
            r[idx] = float(vals['Revenue'])
            s[idx] = int(vals['Initial Inventory'])
            d[idx] = int(vals['Demand'])
        except Exception as e:
            raise RuntimeError(f'Error parsing numeric fields for record {idx}: {e}')
    if not set(r.keys()) == set(s.keys()) == set(d.keys()) == set(I):
        raise RuntimeError('Mismatch in parameter keys for index set I.')
    m = Model()
    m.Params.MIPGap = 0.0001
    x_vars = m.addVars(I, vtype=GRB.INTEGER, lb=0, name='')
    m.addConstrs((x_vars[i] <= s[i] for i in I), name='')
    m.addConstrs((x_vars[i] <= d[i] for i in I), name='')
    m.setObjective(quicksum((r[i] * x_vars[i] for i in I)), GRB.MAXIMIZE)
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for i in I:
            print(f'{x_vars[i].VarName} {x_vars[i].X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = build_and_solve()