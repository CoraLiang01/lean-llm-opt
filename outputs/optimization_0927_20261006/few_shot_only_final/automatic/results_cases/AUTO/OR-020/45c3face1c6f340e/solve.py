def parse_table_records(table, required_columns):
    for col in required_columns:
        if col not in table['columns']:
            raise ValueError(f"Missing required column '{col}' in table {table['table_id']}")
    records = []
    for rec in table['records']:
        values = rec['values']
        entry = {}
        for col in required_columns:
            entry[col] = values[col]
        records.append(entry)
    return records

def get_product_data(CSVQA_DATA):
    table = None
    for t in CSVQA_DATA['tables']:
        if t['table_id'] == 'file_0_view_0':
            table = t
            break
    if table is None:
        raise ValueError("Table with table_id 'file_0_view_0' not found in CSVQA_DATA")
    required_columns = ['Product Name', 'Revenue', 'Demand', 'Initial Inventory']
    records = parse_table_records(table, required_columns)
    products = []
    revenue = {}
    demand = {}
    inventory = {}
    for rec in records:
        prod = rec['Product Name']
        products.append(prod)
        try:
            revenue[prod] = float(rec['Revenue'])
        except Exception:
            raise ValueError(f"Invalid Revenue value for product '{prod}': {rec['Revenue']}")
        try:
            demand[prod] = int(float(rec['Demand']))
        except Exception:
            raise ValueError(f"Invalid Demand value for product '{prod}': {rec['Demand']}")
        try:
            inventory[prod] = int(float(rec['Initial Inventory']))
        except Exception:
            raise ValueError(f"Invalid Initial Inventory value for product '{prod}': {rec['Initial Inventory']}")
    return (products, revenue, demand, inventory)

def build_and_solve_model(CSVQA_DATA):
    (products, revenue, demand, inventory) = get_product_data(CSVQA_DATA)
    if not set(products) == set(revenue.keys()) == set(demand.keys()) == set(inventory.keys()):
        raise ValueError('Mismatch in product identifiers among data dictionaries')
    m = gp.Model('Supermarket_Revenue_Max')
    m.Params.MIPGap = 0.0001
    x_vars = m.addVars(products, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((revenue[i] * x_vars[i] for i in products)), GRB.MAXIMIZE)
    m.addConstrs((x_vars[i] <= demand[i] for i in products), name='')
    m.addConstrs((x_vars[i] <= inventory[i] for i in products), name='')
