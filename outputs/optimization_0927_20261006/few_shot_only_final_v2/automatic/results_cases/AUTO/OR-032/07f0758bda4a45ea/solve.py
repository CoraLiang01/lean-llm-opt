import re
import gurobipy as gp
from gurobipy import GRB

def parse_books_data(CSVQA_DATA):
    table = None
    for t in CSVQA_DATA['tables']:
        if t['table_id'] == 'file_0_view_0':
            table = t
            break
    if table is None:
        raise ValueError("Table with table_id 'file_0_view_0' not found.")
    required_cols = ['Product_Name', 'Revenue', 'Demand', 'Initial Inventory']
    for col in required_cols:
        if col not in table['columns']:
            raise ValueError(f"Required column '{col}' not found in table.")
    books = []
    revenue = {}
    demand = {}
    inventory = {}
    for rec in table['records']:
        vals = rec['values']
        pname = vals['Product_Name']
        if pname is None:
            continue
        if re.search('Books', pname):
            books.append(pname)
            try:
                revenue[pname] = float(vals['Revenue'])
            except Exception:
                raise ValueError(f"Revenue missing or invalid for product '{pname}'")
            try:
                demand[pname] = int(float(vals['Demand']))
            except Exception:
                raise ValueError(f"Demand missing or invalid for product '{pname}'")
            try:
                inventory[pname] = int(float(vals['Initial Inventory']))
            except Exception:
                raise ValueError(f"Initial Inventory missing or invalid for product '{pname}'")
    if not books:
        raise ValueError("No products with 'Books' in Product_Name found.")
    for pname in books:
        if pname not in revenue or pname not in demand or pname not in inventory:
            raise ValueError(f"Missing parameter for product '{pname}'")
    return (books, revenue, demand, inventory)

def build_books_model(CSVQA_DATA):
    (books, revenue, demand, inventory) = parse_books_data(CSVQA_DATA)
    upper_bounds = {i: min(demand[i], inventory[i]) for i in books}
    for i in books:
        if upper_bounds[i] < 0:
            raise ValueError(f"Negative upper bound for product '{i}'")
    m = gp.Model('Books_Revenue_Max')
    x_vars = m.addVars(books, lb=0, ub=[upper_bounds[i] for i in books], vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((revenue[i] * x_vars[i] for i in books)), GRB.MAXIMIZE)
    m.Params.MIPGap = 0.0001
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for v in x_vars.values():
            print(f'{v.VarName}: {v.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = build_books_model(CSVQA_DATA)