import gurobipy as gp
from gurobipy import GRB
import re
table_id = 'file_0_view_0'
tables = CSVQA_DATA['tables']
table = None
for t in tables:
    if t['table_id'] == table_id:
        table = t
        break
if table is None:
    raise ValueError(f'Table {table_id} not found in CSVQA_DATA.')
records = table['records']
product_pattern = re.compile('^S700_')
products = []
revenue = {}
demand = {}
inventory = {}
for rec in records:
    pname = rec['values']['Product Name']
    if product_pattern.match(pname):
        products.append(pname)
        try:
            revenue[pname] = float(rec['values']['Revenue'])
        except Exception:
            raise ValueError(f'Missing or invalid Revenue for product {pname}')
        try:
            demand[pname] = int(float(rec['values']['Demand']))
        except Exception:
            raise ValueError(f'Missing or invalid Demand for product {pname}')
        try:
            inventory[pname] = int(float(rec['values']['Initial Inventory']))
        except Exception:
            raise ValueError(f'Missing or invalid Initial Inventory for product {pname}')
if not products:
    raise ValueError("No products with prefix 'S700_' found.")
for pname in products:
    if pname not in revenue or pname not in demand or pname not in inventory:
        raise ValueError(f'Missing data for product {pname}')

def build_and_solve(products, revenue, demand, inventory):
    m = gp.Model('S700_Revenue_Max')
    x_vars = m.addVars(products, vtype=GRB.INTEGER, lb=0, name='')
    m.setObjective(gp.quicksum((revenue[i] * x_vars[i] for i in products)), GRB.MAXIMIZE)
    m.addConstrs((x_vars[i] <= inventory[i] for i in products), name='')
    m.addConstrs((x_vars[i] <= demand[i] for i in products), name='')
    m.Params.MIPGap = 0.0001
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for var in x_vars.values():
            print(f'{var.VarName}: {var.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
