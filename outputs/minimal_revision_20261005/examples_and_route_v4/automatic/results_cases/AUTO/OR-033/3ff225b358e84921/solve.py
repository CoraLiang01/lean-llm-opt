import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    records = [{'Demand': '765850', 'Initial Inventory': '5627060', 'Product Name': 'Baby Food_255.28', 'Revenue': '255.28'}]
    I = []
    r = {}
    d = {}
    s = {}
    for rec in records:
        prod = rec['Product Name']
        I.append(prod)
        try:
            r[prod] = float(rec['Revenue'])
            d[prod] = int(rec['Demand'])
            s[prod] = int(rec['Initial Inventory'])
        except Exception as e:
            raise ValueError(f'Invalid data for product {prod}: {e}')
    for prod in I:
        if prod not in r or prod not in d or prod not in s:
            raise ValueError(f'Missing data for product {prod}')
    m = gp.Model('Baby_Product_Revenue')
    m.setParam('MIPGap', 0.0001)
    x = m.addVars(I, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((r[i] * x[i] for i in I)), GRB.MAXIMIZE)
    m.addConstrs((x[i] <= s[i] for i in I), name='')
    m.addConstrs((x[i] <= d[i] for i in I), name='')
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for v in m.getVars():
            print(f'{v.VarName}: {v.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()