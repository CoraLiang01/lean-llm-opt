import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    table = CSVQA_DATA['tables'][0]
    records = table['records']
    I = []
    r = {}
    d = {}
    s = {}
    for rec in records:
        vals = rec['values']
        prod = vals['Product Name']
        if prod.casefold().startswith('27in'):
            I.append(prod)
            try:
                r[prod] = float(vals['Revenue'])
                d[prod] = int(vals['Demand'])
                s[prod] = int(vals['Initial Inventory'])
            except Exception as e:
                raise ValueError(f'Invalid data for product {prod}: {e}')
    if not set(I) == set(r) == set(d) == set(s):
        raise ValueError('Missing data for some products in index set I')
    m = gp.Model('27in_inventory_allocation')
    x = m.addVars(I, lb=0, ub=None, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((r[i] * x[i] for i in I)), GRB.MAXIMIZE)
    m.addConstrs((x[i] <= d[i] for i in I), name='')
    m.addConstrs((x[i] <= s[i] for i in I), name='')
    m.Params.MIPGap = 0.0001
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for v in m.getVars():
            print(f'{v.VarName}: {v.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()