import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    table = CSVQA_DATA['tables'][0]
    records = table['records']
    I = []
    r = {}
    d = {}
    s = {}
    for rec in records:
        vals = rec['values']
        product = vals['Product Name']
        I.append(product)
        try:
            r[product] = float(vals['Revenue'])
            d[product] = int(vals['Demand'])
            s[product] = int(vals['Initial Inventory'])
        except Exception as e:
            raise ValueError(f"Missing or invalid data for product '{product}': {e}")
    if not set(I) == set(r) == set(d) == set(s):
        raise ValueError('Mismatch in index sets or missing data.')
    m = gp.Model('Baby_Product_Revenue_Maximization')
    x = m.addVars(I, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((r[i] * x[i] for i in I)), GRB.MAXIMIZE)
    m.addConstrs((x[i] <= d[i] for i in I), name='')
    m.addConstrs((x[i] <= s[i] for i in I), name='')
    m.Params.MIPGap = 0.0001
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for v in m.getVars():
            print(f'{v.VarName}: {v.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()