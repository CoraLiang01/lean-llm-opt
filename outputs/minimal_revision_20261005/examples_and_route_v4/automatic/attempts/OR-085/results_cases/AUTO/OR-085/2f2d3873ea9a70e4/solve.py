import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    table = None
    for t in CSVQA_DATA['tables']:
        if t['table_id'] == 'file_0_view_0':
            table = t
            break
    if table is None:
        raise RuntimeError('Distance matrix table not found.')
    n_locations = len(table['records'])
    N = [str(i + 1) for i in range(n_locations)]
    d = {}
    for (i, rec) in enumerate(table['records']):
        row_label = str(i + 1)
        for col_label in table['columns']:
            if col_label == row_label:
                continue
            val = rec['values'].get(col_label, '')
            if val != '':
                d[row_label, col_label] = float(val)
                d[col_label, row_label] = float(val)
    for i in N:
        for j in N:
            if i != j and (i, j) not in d:
                raise ValueError(f'Missing distance for ({i},{j})')
    x_keys = [(i, j) for i in N for j in N if i != j]
    u_keys = [i for i in N if int(i) >= 2]
    m = gp.Model('TSP_15')
    x = m.addVars(x_keys, vtype=GRB.BINARY, name='')
    u = m.addVars(u_keys, lb=1, ub=n_locations - 1, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((d[i, j] * x[i, j] for (i, j) in x_keys)), GRB.MINIMIZE)
    for i in N:
        m.addConstr(gp.quicksum((x[i, j] for j in N if j != i)) == 1, name=f'leave_{i}')
    for j in N:
        m.addConstr(gp.quicksum((x[i, j] for i in N if i != j)) == 1, name=f'enter_{j}')
    for i in u_keys:
        for j in u_keys:
            if i != j:
                m.addConstr(u[i] - u[j] + n_locations * x[i, j] <= n_locations - 1, name=f'mtz_{i}_{j}')
    m.Params.MIPGap = 0.0001
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for var in m.getVars():
            print(f'{var.VarName}: {var.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()