import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    data = CSVQA_DATA
    table = None
    for t in data['tables']:
        if t['table_id'] == 'file_0_view_0':
            table = t
            break
    if table is None:
        raise RuntimeError("Required table_id 'file_0_view_0' not found in CSVQA_DATA.")
    records = table['records']
    products = []
    labor = {}
    material = {}
    selling_price = {}
    variable_cost = {}
    for rec in records:
        v = rec['values']
        pname = v['Product Name']
        products.append(pname)
        try:
            labor[pname] = float(v['Labor per unit'])
            material[pname] = float(v['Material per unit'])
            selling_price[pname] = float(v['Selling Price'])
            variable_cost[pname] = float(v['Variable Cost'])
        except Exception as e:
            raise ValueError(f"Error parsing record for product '{pname}': {e}")
    L = 1650
    M = 1850
    F = 4500
    m = gp.Model('RedBeanClothingFactory')
    m.setParam('MIPGap', 0.0001)
    x = m.addVars(products, lb=0, vtype=GRB.CONTINUOUS, name='')
    m.setObjective(gp.quicksum(((selling_price[p] - variable_cost[p]) * x[p] for p in products)) - F, GRB.MAXIMIZE)
    m.addConstr(gp.quicksum((labor[p] * x[p] for p in products)) <= L, name='labor_capacity')
    m.addConstr(gp.quicksum((material[p] * x[p] for p in products)) <= M, name='material_capacity')
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for v in m.getVars():
            print(f'{v.VarName}: {v.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()