import gurobipy as gp
from gurobipy import GRB

def solve_problem(CSVQA_DATA):
    warehouses_table = None
    stores_table = None
    cost_table = None
    for t in CSVQA_DATA['tables']:
        if t['table_id'] == 'file_0_view_0':
            warehouses_table = t
        elif t['table_id'] == 'file_1_view_0':
            stores_table = t
        elif t['table_id'] == 'file_2_view_0':
            cost_table = t
    if warehouses_table is None or stores_table is None or cost_table is None:
        raise RuntimeError('Missing required table(s) in CSVQA_DATA.')
    I = []
    f = {}
    u = {}
    for rec in warehouses_table['records']:
        i = rec['values']['Warehouse (i)']
        I.append(i)
        f[i] = float(rec['values']['Opening Cost (fi)'])
        u[i] = float(rec['values']['Capacity (units)'])
    J = []
    d = {}
    for rec in stores_table['records']:
        j = rec['values']['Store (j)']
        J.append(j)
        d[j] = float(rec['values']['Demand (units, dj)'])
    c = {}
    warehouse_id_to_W = {i: f'W{i}' for i in I}
    store_id_to_W = {j: f'W{j}' for j in J}
    for rec in cost_table['records']:
        row_label = rec['values']['Unnamed: 1']
        i = None
        for wi in I:
            if row_label == f'W{wi}':
                i = wi
                break
        if i is None:
            continue
        c[i] = {}
        for j in J:
            col_label = f'W{j}'
            val = rec['values'].get(col_label, None)
            if val is None or val == '':
                raise ValueError(f'Missing transportation cost for warehouse {i}, store {j}')
            c[i][j] = float(val)
    for i in I:
        if i not in c:
            raise ValueError(f'Missing cost row for warehouse {i}')
        for j in J:
            if j not in c[i]:
                raise ValueError(f'Missing cost entry for warehouse {i}, store {j}')
    m = gp.Model('FLP')
    x_keys = [(i, j) for i in I for j in J]
    x = m.addVars(x_keys, lb=0, vtype=GRB.CONTINUOUS, name='')
    y = m.addVars(I, vtype=GRB.BINARY, name='')
    m.setObjective(gp.quicksum((f[i] * y[i] for i in I)) + gp.quicksum((c[i][j] * x[i, j] for (i, j) in x_keys)), GRB.MINIMIZE)
    m.addConstrs((gp.quicksum((x[i, j] for i in I)) == d[j] for j in J), name='')
    m.addConstrs((gp.quicksum((x[i, j] for j in J)) <= u[i] * y[i] for i in I), name='')
    m.Params.MIPGap = 0.0001
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for var in m.getVars():
            print(f'{var.VarName}: {var.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
