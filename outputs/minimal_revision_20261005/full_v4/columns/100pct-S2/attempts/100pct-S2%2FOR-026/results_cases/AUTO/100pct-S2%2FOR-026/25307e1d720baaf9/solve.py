import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    plant_table = None
    for t in CSVQA_DATA['tables']:
        if t['table_id'] == 'file_0_view_0':
            plant_table = t
            break
    if plant_table is None:
        raise RuntimeError('Plant table not found')
    plants = []
    f = {}
    K = {}
    c = {}
    for rec in plant_table['records']:
        v = rec['values']
        plant_id = v['facility_id']
        plants.append(plant_id)
        f[plant_id] = float(v['fixed_opening_cost'])
        K[plant_id] = float(v['facility_capacity'])
        c[plant_id] = {}
        for j in range(1, 16):
            cust_id = f'C{j}'
            col = f'transportation_cost_to_{cust_id}'
            c[plant_id][cust_id] = float(v[col])
    cust_table = None
    for t in CSVQA_DATA['tables']:
        if t['table_id'] == 'file_1_view_0':
            cust_table = t
            break
    if cust_table is None:
        raise RuntimeError('Customer table not found')
    customers = []
    d = {}
    for rec in cust_table['records']:
        v = rec['values']
        cust_id = v['customer_id']
        customers.append(cust_id)
        d[cust_id] = float(v['demand_units'])
    for i in plants:
        if i not in f or i not in K or i not in c:
            raise ValueError(f'Missing plant data for {i}')
        for j in customers:
            if j not in c[i]:
                raise ValueError(f'Missing transportation cost for plant {i}, customer {j}')
    for j in customers:
        if j not in d:
            raise ValueError(f'Missing demand for customer {j}')
    m = gp.Model('FLP')
    m.setParam('MIPGap', 0.0001)
    x = m.addVars(plants, customers, lb=0, vtype=GRB.CONTINUOUS, name='')
    y = m.addVars(plants, vtype=GRB.BINARY, name='')
    m.setObjective(gp.quicksum((f[i] * y[i] for i in plants)) + gp.quicksum((c[i][j] * x[i, j] for i in plants for j in customers)), GRB.MINIMIZE)
    m.addConstrs((gp.quicksum((x[i, j] for i in plants)) == d[j] for j in customers), name='')
    m.addConstrs((gp.quicksum((x[i, j] for j in customers)) <= K[i] * y[i] for i in plants), name='')
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for var in m.getVars():
            print(f'{var.VarName}: {var.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
