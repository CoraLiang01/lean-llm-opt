import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    shelves = []
    c_s = {}
    for rec in CSVQA_DATA['tables'][0]['records']:
        s = rec['values']['resource_id']
        shelves.append(s)
        c_s[s] = int(rec['values']['resource_capacity'])
    products = []
    v_p = {}
    a_p = {}
    for rec in CSVQA_DATA['tables'][1]['records']:
        p = rec['values']['item_name']
        products.append(p)
        v_p[p] = int(rec['values']['item_value'])
        a_p[p] = int(rec['values']['resource_requirement'])
    m = gp.Model('BigMart_Shelf_Allocation')
    m.setParam('MIPGap', 0.0001)
    x = m.addVars(shelves, products, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((v_p[p] * x[s, p] for s in shelves for p in products)), GRB.MAXIMIZE)
    m.addConstrs((gp.quicksum((a_p[p] * x[s, p] for p in products)) <= c_s[s] for s in shelves), name='')
    m.optimize()
    return m
m = solve_problem()
