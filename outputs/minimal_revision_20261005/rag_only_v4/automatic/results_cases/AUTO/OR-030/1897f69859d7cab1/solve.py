import gurobipy as gp
from gurobipy import GRB

def solve_problem(CSVQA_DATA):
    table = None
    for t in CSVQA_DATA['tables']:
        if t['table_id'] == 'file_0_view_0':
            table = t
            break
    if table is None:
        raise RuntimeError('Required table_id file_0_view_0 not found in CSVQA_DATA.')
    records = table['records']
    I = []
    for rec in records:
        pname = rec['values']['Product Name']
        if pname.casefold().startswith('fdk57'):
            I.append(rec['source_row'])
    r = {}
    d = {}
    s = {}
    for rec in records:
        key = rec['source_row']
        pname = rec['values']['Product Name']
        if key not in I:
            continue
        try:
            r[key] = float(rec['values']['Revenue'])
            d[key] = int(rec['values']['Demand'])
            s[key] = int(rec['values']['Initial Inventory'])
        except Exception as e:
            raise RuntimeError(f'Invalid data for record {key}: {e}')
    for key in I:
        if key not in r or key not in d or key not in s:
            raise RuntimeError(f'Missing parameter for index {key}')
    m = gp.Model()
    m.Params.MIPGap = 0.0001
    x = m.addVars(I, lb=0, ub={i: min(d[i], s[i]) for i in I}, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((r[i] * x[i] for i in I)), GRB.MAXIMIZE)
    m.addConstrs((x[i] <= d[i] for i in I), name='')
    m.addConstrs((x[i] <= s[i] for i in I), name='')
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(m.ObjVal)
        for i in I:
            print(x[i].VarName, x[i].X)
    else:
        print(m.Status)
    return m
m = solve_problem(CSVQA_DATA)