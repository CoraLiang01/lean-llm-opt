import gurobipy as gp
from gurobipy import GRB

def solve_problem(CSVQA_DATA):
    table = None
    for t in CSVQA_DATA['tables']:
        if t['table_id'] == 'file_0_view_0':
            table = t
            break
    if table is None:
        raise RuntimeError('Required table_id file_0_view_0 not found in CSVQA_DATA.')
    I = []
    r = {}
    d = {}
    s = {}
    for rec in table['records']:
        vals = rec['values']
        i = rec['source_row']
        if not vals['Product Name'].casefold().startswith('FDK57'.casefold()):
            continue
        I.append(i)
        try:
            r[i] = float(vals['Revenue'])
            d[i] = int(vals['Demand'])
            s[i] = int(vals['Initial Inventory'])
        except Exception as e:
            raise RuntimeError(f'Invalid data for record {i}: {e}')
    if not set(I) == set(r.keys()) == set(d.keys()) == set(s.keys()):
        raise RuntimeError('Missing data for some indices in I.')
    m = gp.Model()
    x = m.addVars(I, lb=0, ub={i: min(d[i], s[i]) for i in I}, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((r[i] * x[i] for i in I)), GRB.MAXIMIZE)
    for i in I:
        m.addConstr(x[i] <= d[i], name=f'demand_{i}')
        m.addConstr(x[i] <= s[i], name=f'inventory_{i}')
        m.addConstr(x[i] >= 0, name=f'nonneg_{i}')
    m.Params.MIPGap = 0.0001
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for i in I:
            print(f'{x[i].VarName} {x[i].X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem(CSVQA_DATA)