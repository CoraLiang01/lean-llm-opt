import gurobipy as gp
from gurobipy import GRB

def solve_problem():
    data = [rec['values'] for rec in CSVQA_DATA['tables'][0]['records'] if 'Organ'.casefold() in rec['values']['Sub Category'].casefold()]
    items = []
    revenue = {}
    demand = {}
    inventory = {}
    for rec in data:
        key = rec['Sub Category']
        try:
            A = float(rec['Revenue'])
            d = int(float(rec['Demand']))
            I = int(float(rec['Initial Inventory']))
        except Exception as e:
            raise ValueError(f'Invalid data for {key}: {e}')
        items.append(key)
        revenue[key] = A
        demand[key] = d
        inventory[key] = I
    if not set(items) == set(revenue) == set(demand) == set(inventory):
        raise ValueError('Mismatch in index sets for items, revenue, demand, or inventory.')
    m = gp.Model('Organ_Product_Revenue')
    m.setParam('MIPGap', 0.0001)
    x = m.addVars(items, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gp.quicksum((revenue[i] * x[i] for i in items)), GRB.MAXIMIZE)
    m.addConstrs((x[i] <= inventory[i] for i in items), name='')
    m.addConstrs((x[i] <= demand[i] for i in items), name='')
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for v in m.getVars():
            print(f'{v.VarName}: {v.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()