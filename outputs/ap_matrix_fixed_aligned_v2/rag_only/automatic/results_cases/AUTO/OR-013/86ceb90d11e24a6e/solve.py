from gurobipy import Model, GRB, quicksum
table = None
for t in CSVQA_DATA['tables']:
    if t['table_id'] == 'file_0_view_0':
        table = t
        break
if table is None:
    raise RuntimeError("Required table_id 'file_0_view_0' not found in CSVQA_DATA.")
I = []
r = {}
d = {}
s = {}
for rec in table['records']:
    vals = rec['values']
    pname = vals['Product Name']
    if not pname.startswith('4U'):
        continue
    try:
        revenue = float(vals['Revenue'])
        demand = int(vals['Demand'])
        inventory = int(vals['Initial Inventory'])
    except Exception as e:
        raise ValueError(f'Invalid data for product {pname}: {e}')
    I.append(pname)
    r[pname] = revenue
    d[pname] = demand
    s[pname] = inventory
if not set(r.keys()) == set(d.keys()) == set(s.keys()) == set(I):
    raise ValueError('Mismatch in index sets for parameters r, d, s, or I.')

def build_model():
    m = Model()
    m.Params.MIPGap = 0.0001
    x_vars = m.addVars(I, vtype=GRB.INTEGER, lb=0, ub=None, name='')
    for i in I:
        m.addConstr(x_vars[i] <= d[i], name='')
        m.addConstr(x_vars[i] <= s[i], name='')
    m.setObjective(quicksum((r[i] * x_vars[i] for i in I)), GRB.MAXIMIZE)
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal {m.ObjVal}')
        for i in I:
            print(f'{x_vars[i].VarName} {x_vars[i].X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = build_model()