import gurobipy
from gurobipy import GRB

def solve_problem():
    m = gurobipy.Model()
    m.setParam('MIPGap', 1e-06)
    table = None
    for tbl in CSVQA_DATA['tables']:
        if tbl.get('table_id') == 'file_0_view_0':
            table = tbl
            break
    if table is None:
        raise ValueError("Required table 'file_0_view_0' not found in CSVQA_DATA")
    records = table.get('records', [])
    if not records:
        raise ValueError("No records returned for table 'file_0_view_0'")
    I = []
    revenue = {}
    demand = {}
    inventory = {}
    for rec in records:
        vals = rec.get('values', {})
        id_num = vals.get('id_number')
        if id_num is None:
            raise ValueError("Record missing 'id_number'")
        if not id_num.startswith('id999'):
            continue
        rev_str = vals.get('Revenue')
        dem_str = vals.get('Demand')
        inv_str = vals.get('Initial Inventory')
        if rev_str is None or dem_str is None or inv_str is None:
            raise ValueError(f'Missing data for product {id_num}')
        try:
            rev = float(rev_str)
            dem = int(dem_str)
            inv = int(inv_str)
        except Exception as e:
            raise ValueError(f'Invalid numeric value for product {id_num}: {e}')
        I.append(id_num)
        revenue[id_num] = rev
        demand[id_num] = dem
        inventory[id_num] = inv
    if not I:
        raise ValueError('No id999 products found in data')
    for i in I:
        if i not in revenue or i not in demand or i not in inventory:
            raise ValueError(f'Incomplete data for product {i}')
    x = m.addVars(I, lb=0, vtype=GRB.INTEGER, name='')
    m.setObjective(gurobipy.quicksum((revenue[i] * x[i] for i in I)), GRB.MAXIMIZE)
    m.addConstrs((x[i] <= inventory[i] for i in I), name='')
    m.addConstrs((x[i] <= demand[i] for i in I), name='')
    m.optimize()
    if m.Status == GRB.OPTIMAL:
        print(f'ObjVal: {m.ObjVal}')
        for var in m.getVars():
            print(f'{var.VarName}: {var.X}')
    else:
        print(f'Solver status: {m.Status}')
    return m
m = solve_problem()