import gurobipy
from gurobipy import GRB

def solve_problem():
    tables = CSVQA_DATA.get('tables', [])
    table = None
    for t in tables:
        if t.get('table_id') == 'file_0_view_0':
            table = t
            break
    if table is None:
        raise ValueError("Required table 'file_0_view_0' not found in CSVQA_DATA")
    records = table.get('records', [])
    if not records:
        raise ValueError('No records found in the cost table')
    managers = [rec['values']['Manager'] for rec in records]
    project_columns = [col for col in table.get('columns', []) if col.endswith(' Cost')]
    if len(project_columns) != 7:
        raise ValueError('Expected 7 project cost columns, found {}'.format(len(project_columns)))
    projects = [col.replace(' Cost', '') for col in project_columns]
    cost = {}
    for rec in records:
        m = rec['values']['Manager']
        cost[m] = {}
        for p_col in project_columns:
            p = p_col.replace(' Cost', '')
            val_str = rec['values'].get(p_col)
            if val_str is None:
                raise ValueError(f'Missing cost for manager {m} on project {p}')
            try:
                val = float(val_str)
            except ValueError:
                raise ValueError(f'Invalid numeric value for manager {m} on project {p}: {val_str}')
            cost[m][p] = val
    for m in managers:
        if set(cost[m].keys()) != set(projects):
            missing = set(projects) - set(cost[m].keys())
            raise ValueError(f'Manager {m} missing costs for projects: {missing}')
    model = gurobipy.Model()
    model.setParam('MIPGap', 1e-06)
    var_keys = [(m, p) for m in managers for p in projects]
    x = model.addVars(var_keys, vtype=GRB.BINARY, name='')
    obj_expr = gurobipy.quicksum((cost[m][p] * x[m, p] for m in managers for p in projects))
    model.setObjective(obj_expr, GRB.MINIMIZE)
    model.addConstrs((gurobipy.quicksum((x[m, p] for p in projects)) == 1 for m in managers), name='')
    model.addConstrs((gurobipy.quicksum((x[m, p] for m in managers)) == 1 for p in projects), name='')
    model.optimize()
    return model
m = solve_problem()