#!/usr/bin/env python3
"""
build_largescale_labels.py
==========================
Generate the ground-truth labels for Air-NRM-CA-LS (the large-scale SBLP set).

    python build_largescale_labels.py --check    # solve + verify, write nothing
    python build_largescale_labels.py            # write .lp files and CA_answer.csv
    python build_largescale_labels.py --solver highs

Then wire the objectives into the query file and enable scoring:

    python link_air_nrm_labels.py --check
    python link_air_nrm_labels.py

Why this exists
---------------
`run_all_Generate_Label_Large_Scale_Or.ipynb` is the house label generator, but
it covers NRM / RA / TP / UFLP / AP under Test_Dataset/Large-scale-or -- there
is no SBLP section, and `run_all_*_obj.py` is scoped the same way. The Air-NRM
`.lp` files under small_scale/SBLP_CA_Label say "Generated by Cardinal
Operations", i.e. they were produced with COPT outside this repository, and no
equivalent exists for the large-scale set. `exp_config.yaml` records that as
`Air-NRM-CA-LS: {gold_objective: null}`, which makes the dataset unscorable.

This closes that gap in the same shape as the reference notebook: one
`sblp_ca_lp(...)` builder, one loop over the instances, `model.write(...lp)`,
plus a `CA_answer.csv` whose schema matches small_scale/SBLP_CA_Label so
`link_air_nrm_labels.py` can pick it up unchanged.

Formulation
-----------
Gallego, Ratliff and Shebalov (2015) eq. (7), the SBLP:

    variables   x[OD, time, product]                one per fare family
                x_o[OD]                             one per OD
    objective   max  sum avg_price * x
    capacity    sum_j capacity_consum[j] * x[OD,time,j]  <=  flight_capacity[OD,time]
    balance     ratio_0[OD] * x_o[OD]
                  + sum ratio[OD,time,j] * x[OD,time,j]  =  avg_pax[OD]
    scale       x[OD,time,j] / value[OD,time,j]  -  x_o[OD] / value_0[OD]  <=  0
    x, x_o >= 0

Cells whose `ratio` (v2) is exactly 0 drop out of the balance constraint, as
they do in the reference labels.

Note the scale constraint carries `value_0` -- the paper (p.222) states it as
`x_lk/v_lk <= x_l0/v_l0`. In small_scale/v1.csv `no_purchase` is 1 on every row,
so `x_j <= v_j * x_o` and `x_j <= (v_j/v_0) * x_o` are indistinguishable there
and the reference .lp files show the first form. The large-scale v1 is on a
share-like scale where `no_purchase` runs 0.119 to 0.556, so dropping v_0 would
silently rescale every scale constraint. `--validate` cannot catch this on its
own for exactly that reason; the paper is the authority here.

Every coefficient the label depends on is parsed back out of the query text --
the flight list, the per-product capacity consumption, the capacity haircut --
rather than re-read from build_queries.py's constants. A label built from the
generator could silently disagree with the question actually asked; a label
built from the question cannot.

Solver: gurobipy, which is what the rest of the repository uses -- requirements
pins it, score_runs.py grades the agent's answers with it, and every
run_all_*_obj.py check is built on it. Labels and answers should come out of
the same solver. COPT and scipy/HiGHS are accepted as fallbacks and, when
importable, are used to cross-check the objective; --solver pins one.

The pip wheel's limited licence (2000 variables, 2000 constraints) covers every
instance here -- the largest is 421 variables and 519 constraints -- so no
licence file is required.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parent
BASE = REPO_ROOT / "Test_Dataset" / "Air_NRM" / "large_scale"
QUERY = BASE / "query_CA.csv"
LABEL_DIR = BASE / "SBLP_CA_Label"

PRODUCTS = ["Eco_flexi", "Eco_standard", "Eco_value", "Eco_lite"]
SHORT = {"Eco_flexi": "f", "Eco_standard": "s", "Eco_value": "v", "Eco_lite": "l"}

TIME_WINDOWS = [
    ("(12pm~6pm)", 12 * 60, 18 * 60),
    ("(6pm~10pm)", 18 * 60, 22 * 60),
    ("(10pm~8am)", 22 * 60, 8 * 60),  # wraps midnight
    ("(8am~12pm)", 8 * 60, 12 * 60),
]

CLAUSE = re.compile(
    r"\(OD\s*=\s*(\('[^']*',\s*'[^']*'\))\s*AND\s*Departure Time='(\d{1,2}:\d{2})'\)"
)
CONSUME = re.compile(r"each (Eco_\w+) ticket consumes ([\d.]+) unit")
HAIRCUT = re.compile(r"capacity is (\d+(?:\.\d+)?)% of its weekly economy capacity")
TIME_LIMIT_S = 300


def window_of(time: str) -> str:
    minutes = int(time.split(":")[0]) * 60 + int(time.split(":")[1])
    for label, lo, hi in TIME_WINDOWS:
        if lo < hi:
            if lo <= minutes < hi:
                return label
        elif minutes >= lo or minutes < hi:
            return label
    raise ValueError(f"unbucketable departure time {time!r}")


# ─────────────────────────────────────────────────────────── data + parsing ──

class Data:
    """The five CSVs, indexed the way the formulation needs them."""

    def __init__(self, base: Path, flat_capacity: float | None = None) -> None:
        flight = pd.read_csv(base / "flight.csv")
        self.price = flight.set_index(
            ["Oneway_OD", "Departure Time", "Oneway_Product"])["Avg Price"]
        self.v1 = pd.read_csv(base / "v1.csv").set_index("OD Pairs")

        # Products and their short codes come from v1's own column names, so the
        # same code path serves the 2-product small-scale set and the 4-product
        # large-scale one. That matters: --validate is only evidence if it
        # exercises the code that actually builds the labels.
        self.products: list[str] = []
        for column in self.v1.columns:
            if "*" in column:
                name = column.split("*")[0]
                if name not in self.products:
                    self.products.append(name)
        self.short = {p: p.split("_")[-1][0] for p in self.products}
        if len(set(self.short.values())) != len(self.products):
            raise RuntimeError(f"short codes collide for {self.products}")

        # small_scale ships no flight_capacity.csv -- its .lp files hard-code
        # 187 seats on every flight.
        cap_path = base / "flight_capacity.csv"
        if cap_path.exists():
            cap = pd.read_csv(cap_path)
            self.capacity = cap.set_index(
                ["Oneway_OD", "Departure Time"])["Y Seats/Week"]
            self.flat_capacity = None
        else:
            if flat_capacity is None:
                raise RuntimeError(f"no flight_capacity.csv in {base} and no "
                                   f"flat capacity given")
            self.capacity = None
            self.flat_capacity = float(flat_capacity)
        self.v2 = pd.read_csv(base / "v2.csv").set_index("OD Pairs")
        self.demand = pd.read_csv(base / "od_demand.csv").set_index("Oneway_OD")["Avg Pax"]
        self.pairs = set(zip(flight["Oneway_OD"], flight["Departure Time"]))


class Instance:
    """One query row, parsed into the coefficient dictionaries the SBLP needs.

    Key shapes match small_scale/SBLP_CA_Label/CA_answer.csv:
        avg_price / value_list / ratio_list : (OD, time, short_product)
        value_0_list / ratio_0_list         : (OD, 'o')
        avg_pax / flight_capacity           : OD  /  (OD, time)
    """

    def __init__(self, index: int, text: str, data: Data) -> None:
        self.index = index
        self.flights = [(od.strip(), t.strip()) for od, t in CLAUSE.findall(text)]

        if len(self.flights) != text.count("AND Departure Time="):
            raise ValueError(f"query {index}: a flight clause is written in an "
                             f"unexpected format and would be dropped silently")
        if len(set(self.flights)) != len(self.flights):
            raise ValueError(f"query {index}: a flight is listed twice")
        unknown = [p for p in self.flights if p not in data.pairs]
        if unknown:
            raise ValueError(f"query {index}: not a row of flight.csv -> {unknown[:3]}")

        # The small-scale queries say "Eco_flex" where v1.csv says "Eco_flexi",
        # so an exact-name lookup would miss. Prefix matching either way, and a
        # hard failure if a product still has no coefficient.
        found = dict(CONSUME.findall(text))
        self.capacity_consum = {}
        for p in data.products:
            hit = next((k for k in found if k == p), None)
            if hit is None:
                hit = next((k for k in found if p.startswith(k) or k.startswith(p)), None)
            if hit is None:
                raise ValueError(f"query {index}: no capacity consumption for {p!r}")
            self.capacity_consum[data.short[p]] = float(found[hit])

        cut = HAIRCUT.search(text)
        self.capacity_fraction = float(cut.group(1)) / 100.0 if cut else 1.0

        self.ods = sorted({od for od, _ in self.flights})
        self.products, self.short = data.products, data.short
        self.n_variables = len(data.products) * len(self.flights) + len(self.ods)

        self.avg_price, self.value_list, self.ratio_list = {}, {}, {}
        for od, t in self.flights:
            window = window_of(t)
            for p in data.products:
                key = (od, t, data.short[p])
                self.avg_price[key] = float(data.price[(od, t, p)])
                self.value_list[key] = float(data.v1.loc[od, f"{p}*{window}"])
                self.ratio_list[key] = float(data.v2.loc[od, f"{p}*{window}"])

        # v1's own no_purchase, not a hard-coded 1: the scale constraint is
        # x_j/v_j <= x_o/v_0 (paper p.222), and this v1 does not normalise
        # v_0 to 1 the way the small-scale reference file does.
        self.value_0_list = {(od, "o"): float(data.v1.loc[od, "no_purchase"])
                             for od in self.ods}
        self.ratio_0_list = {(od, "o"): float(data.v2.loc[od, "no_purchase"])
                             for od in self.ods}
        self.avg_pax = {od: float(data.demand[od]) for od in self.ods}
        self.flight_capacity = {
            (od, t): (data.flat_capacity if data.capacity is None
                      else float(data.capacity[(od, t)])) * self.capacity_fraction
            for od, t in self.flights
        }

    def var_name(self, od: str, time: str, short: str) -> str:
        return f"x_{od}_{time}_{short}".replace(" ", "_")

    def zero_name(self, od: str) -> str:
        return f"x_{od}_0".replace(" ", "_")

    def information(self) -> str:
        """The compact summary CA_answer.csv carries.

        small_scale puts the whole parameter dump in this column and gets away
        with it at 8 cells per instance (4,739 characters). At 98 flights x 4
        fare families the same dump is 57,888 characters, and a spreadsheet
        cell tops out at 32,767 -- rows 8 onward render as garbage in Excel.

        So this column keeps only what a reader needs to identify the instance,
        which is also everything link_air_nrm_labels.py's alignment check reads
        (the departure times). The full dump goes to CA_parameters.json, where
        size is nobody's problem.
        """
        return str({
            "flights": self.flights,
            "n_ods": len(self.ods),
            "n_variables": self.n_variables,
            "capacity_consum": self.capacity_consum,
            "capacity_fraction": self.capacity_fraction,
        })

    def parameters(self) -> dict:
        """The full parameter dump, written to CA_parameters.json."""
        return {
            "avg_price": {str(k): v for k, v in self.avg_price.items()},
            "value_list": {str(k): v for k, v in self.value_list.items()},
            "ratio_list": {str(k): v for k, v in self.ratio_list.items()},
            "value_0_list": {str(k): v for k, v in self.value_0_list.items()},
            "ratio_0_list": {str(k): v for k, v in self.ratio_0_list.items()},
            "avg_pax": self.avg_pax,
            "flight_capacity": {str(k): v for k, v in self.flight_capacity.items()},
            "capacity_consum": self.capacity_consum,
        }


# ─────────────────────────────────────────────────────────────── solvers ─────

def sblp_ca_lp_copt(inst: Instance, lp_path: Path | None):
    from coptpy import Envr, COPT

    model = Envr().createModel(f"SBLP_CA_LS_{inst.index}")
    x = {k: model.addVar(lb=0.0, name=inst.var_name(*k)) for k in inst.avg_price}
    x_o = {od: model.addVar(lb=0.0, name=inst.zero_name(od)) for od in inst.ods}

    model.setObjective(
        sum(inst.avg_price[k] * x[k] for k in x), sense=COPT.MAXIMIZE)

    for od, t in inst.flights:
        model.addConstr(
            sum(inst.capacity_consum[s] * x[(od, t, s)] for s in inst.short.values())
            <= inst.flight_capacity[(od, t)],
            name=f"capacity_constraint_{od}_{t}")
        for s in inst.short.values():
            model.addConstr(
                inst.value_list[(od, t, s)] * x_o[od]
                - inst.value_0_list[(od, "o")] * x[(od, t, s)] >= 0,
                name=f"scale_constraint_{od}_{t}_{s}")
    for od in inst.ods:
        terms = [inst.ratio_list[k] * x[k]
                 for k in x if k[0] == od and inst.ratio_list[k] != 0.0]
        model.addConstr(sum(terms) + inst.ratio_0_list[(od, "o")] * x_o[od]
                        == inst.avg_pax[od], name=f"balance_constraint_{od}")

    model.setParam(COPT.Param.TimeLimit, TIME_LIMIT_S)
    model.setParam(COPT.Param.Logging, 0)
    model.solve()
    if model.status != COPT.OPTIMAL:
        raise RuntimeError(f"instance {inst.index}: COPT status {model.status}")
    if lp_path is not None:
        lp_path.parent.mkdir(parents=True, exist_ok=True)
        model.write(str(lp_path))
    solution = {v.name: v.x for v in list(x.values()) + list(x_o.values()) if v.x > 1e-9}
    return float(model.objval), solution


def sblp_ca_lp_gurobi(inst: Instance, lp_path: Path | None):
    import gurobipy as gp
    from gurobipy import GRB

    model = gp.Model(f"SBLP_CA_LS_{inst.index}")
    model.setParam("OutputFlag", 0)
    model.setParam("TimeLimit", TIME_LIMIT_S)
    x = {k: model.addVar(lb=0.0, name=inst.var_name(*k)) for k in inst.avg_price}
    x_o = {od: model.addVar(lb=0.0, name=inst.zero_name(od)) for od in inst.ods}

    model.setObjective(gp.quicksum(inst.avg_price[k] * x[k] for k in x), GRB.MAXIMIZE)
    for od, t in inst.flights:
        model.addConstr(
            gp.quicksum(inst.capacity_consum[s] * x[(od, t, s)] for s in inst.short.values())
            <= inst.flight_capacity[(od, t)],
            name=f"capacity_constraint_{od}_{t}")
        for s in inst.short.values():
            model.addConstr(
                inst.value_list[(od, t, s)] * x_o[od]
                - inst.value_0_list[(od, "o")] * x[(od, t, s)] >= 0,
                name=f"scale_constraint_{od}_{t}_{s}")
    for od in inst.ods:
        terms = [inst.ratio_list[k] * x[k]
                 for k in x if k[0] == od and inst.ratio_list[k] != 0.0]
        model.addConstr(gp.quicksum(terms) + inst.ratio_0_list[(od, "o")] * x_o[od]
                        == inst.avg_pax[od], name=f"balance_constraint_{od}")

    model.optimize()
    if model.Status != GRB.OPTIMAL:
        raise RuntimeError(f"instance {inst.index}: Gurobi status {model.Status}")
    if lp_path is not None:
        lp_path.parent.mkdir(parents=True, exist_ok=True)
        # LP format reserves ':' as the name/expression separator, so Gurobi
        # rewrites x_('710',_'865')_16:25_f as ..._16_25_f on the way out. The
        # small_scale reference files keep the colon because COPT is laxer
        # here. Only the .lp text differs -- X_sol_label below is built from
        # VarName, which still carries the colon, so the machine-readable
        # artefact matches the reference convention either way.
        model.write(str(lp_path))
    solution = {v.VarName: v.X for v in model.getVars() if v.X > 1e-9}
    return float(model.ObjVal), solution


def sblp_ca_lp_highs(inst: Instance, lp_path: Path | None):
    """scipy/HiGHS fallback. Cannot write .lp; used for cross-checking."""
    from scipy.optimize import linprog

    cells = list(inst.avg_price)
    idx = {c: i for i, c in enumerate(cells)}
    n = len(cells)
    zero = {od: n + k for k, od in enumerate(inst.ods)}
    size = n + len(inst.ods)

    obj = np.zeros(size)
    for c in cells:
        obj[idx[c]] = -inst.avg_price[c]

    a_ub, b_ub = [], []
    for od, t in inst.flights:
        row = np.zeros(size)
        for s in inst.short.values():
            row[idx[(od, t, s)]] = inst.capacity_consum[s]
        a_ub.append(row)
        b_ub.append(inst.flight_capacity[(od, t)])
    for c in cells:
        row = np.zeros(size)
        row[idx[c]] = inst.value_0_list[(c[0], "o")]
        row[zero[c[0]]] = -inst.value_list[c]
        a_ub.append(row)
        b_ub.append(0.0)

    a_eq, b_eq = [], []
    for od in inst.ods:
        row = np.zeros(size)
        for c in cells:
            if c[0] == od:
                row[idx[c]] = inst.ratio_list[c]
        row[zero[od]] = inst.ratio_0_list[(od, "o")]
        a_eq.append(row)
        b_eq.append(inst.avg_pax[od])

    res = linprog(obj, np.array(a_ub), np.array(b_ub), np.array(a_eq),
                  np.array(b_eq), bounds=(0, None), method="highs")
    if not res.success:
        raise RuntimeError(f"instance {inst.index}: HiGHS says {res.message}")
    names = [inst.var_name(*c) for c in cells] + [inst.zero_name(o) for o in inst.ods]
    solution = {nm: float(v) for nm, v in zip(names, res.x) if v > 1e-9}
    return float(-res.fun), solution


# Order matters: the first importable one is the default. gurobipy is the
# repository's solver everywhere else -- requirements.txt pins gurobipy==12.0.1,
# score_runs.py executes the agent's answers through it, and every
# run_all_*_obj.py label check uses it -- so the labels should come from the
# same solver the answers are graded with.
#
# No licence file is needed at this size. The pip wheel ships a limited licence
# good for 2000 variables and 2000 constraints; the largest instance here is
# 421 variables and 519 constraints (98 capacity + 392 scale + 29 balance), so
# it fits with room to spare. A full licence only becomes necessary if the
# ladder in build_queries.py is pushed past roughly 490 flights.
SMALL = REPO_ROOT / "Test_Dataset" / "Air_NRM" / "small_scale"
SMALL_FLAT_CAPACITY = 187.0   # hard-coded in small_scale/SBLP_CA_Label/*.lp


SOLVERS = {"gurobi": sblp_ca_lp_gurobi, "copt": sblp_ca_lp_copt, "highs": sblp_ca_lp_highs}
MODULES = {"gurobi": "gurobipy", "copt": "coptpy", "highs": "scipy"}


def available() -> list[str]:
    out = []
    for name, module in MODULES.items():
        try:
            __import__(module)
            out.append(name)
        except Exception:
            pass
    return out


def validate(solver: str) -> int:
    """Rebuild the small-scale labels and compare against the shipped ones.

    small_scale/SBLP_CA_Label/CA_answer.csv was produced with COPT outside this
    repository. Reproducing it through the same Instance/solver path used for
    the large-scale labels is the only independent evidence that the
    formulation here is the intended one, rather than merely self-consistent.

    One thing it cannot check: small_scale/v1.csv has no_purchase == 1 on every
    row, so the scale constraint's v_0 divisor is invisible to this test. That
    coefficient rests on the paper (p.222), not on this reproduction.
    """
    query = pd.read_csv(SMALL / "query_CA.csv")
    reference = pd.read_csv(SMALL / "SBLP_CA_Label" / "CA_answer.csv")
    data = Data(SMALL, flat_capacity=SMALL_FLAT_CAPACITY)
    print(f"validate   : {SMALL.relative_to(REPO_ROOT)}  "
          f"({len(query)} instances, products {data.products})")
    if (data.v1["no_purchase"] != 1).any():
        print("  note: no_purchase is not 1 here, so this run does exercise v_0")
    print(f"{'#':>3} {'flights':>8} {'rebuilt':>16} {'shipped Obj_label':>19} {'rel err':>10}")

    worst, bad = 0.0, 0
    for i, text in enumerate(query["Query"], start=1):
        inst = Instance(i, text, data)
        value, _ = SOLVERS[solver](inst, None)
        gold = float(reference["Obj_label"].iloc[i - 1])
        rel = abs(value - gold) / max(abs(gold), 1.0)
        worst = max(worst, rel)
        bad += rel >= 1e-6
        print(f"{i:>3} {len(inst.flights):>8} {value:>16,.2f} {gold:>19,.2f} "
              f"{rel:>10.1e}" + ("" if rel < 1e-6 else "  <<<"))
    print()
    if bad:
        print(f"VALIDATE: FAIL — {bad}/{len(query)} instances differ "
              f"(worst {worst:.1e}). The formulation does not match the "
              f"reference labels; do not trust the large-scale output.")
        return 1
    print(f"VALIDATE: PASS — {len(query)}/{len(query)} reproduced "
          f"(worst relative error {worst:.1e})")
    return 0


# ────────────────────────────────────────────────────────────────── main ─────

def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--query", type=Path, default=QUERY)
    ap.add_argument("--data-dir", type=Path, default=BASE)
    ap.add_argument("--out-dir", type=Path, default=LABEL_DIR)
    ap.add_argument("--solver", choices=list(SOLVERS), default=None,
                    help="default: first available of copt, gurobi, highs")
    ap.add_argument("--check", action="store_true",
                    help="solve and verify, but write nothing")
    ap.add_argument("--no-validate", action="store_true",
                    help="skip the small-scale reproduction check")
    args = ap.parse_args()

    have = available()
    if not have:
        sys.exit("ERROR: none of coptpy / gurobipy / scipy is importable; "
                 "pip install -r requirements.txt")
    primary = args.solver or have[0]
    if primary not in have:
        sys.exit(f"ERROR: --solver {primary} requested but {MODULES[primary]} "
                 f"is not importable (available: {', '.join(have)})")
    cross = [s for s in have if s != primary]

    if not args.no_validate:
        if validate(primary) != 0:
            return 1
        print()

    data = Data(args.data_dir)
    frame = pd.read_csv(args.query)

    print(f"query file : {args.query}  ({len(frame)} instances)")
    print(f"solver     : {primary}" +
          (f"   (cross-checked against {', '.join(cross)})" if cross else ""))
    print(f"output     : {args.out_dir}" + ("  [--check: nothing written]"
                                            if args.check else ""))
    print()
    print(f"{'#':>3} {'flights':>8} {'ODs':>4} {'vars':>5} {'consumption':>16} "
          f"{'cap%':>5} {'Obj_label':>16} {'agree':>9}")

    rows, summary, parameters, problems = [], [], [], 0
    for i, text in enumerate(frame["Query"], start=1):
        inst = Instance(i, text, data)
        lp_path = None if args.check or primary == "highs" else args.out_dir / f"{i}.lp"
        objective, solution = SOLVERS[primary](inst, lp_path)

        agree = "-"
        for other in cross:
            value, _ = SOLVERS[other](inst, None)
            rel = abs(value - objective) / max(abs(objective), 1.0)
            if rel >= 1e-6:
                agree = f"NO {rel:.1e}"
                problems += 1
                break
            agree = "yes"

        # The query file's own variable count must match the model just built,
        # or the file is labelling a different problem than it states.
        if "n_variables" in frame.columns:
            declared = int(frame["n_variables"].iloc[i - 1])
            if declared != inst.n_variables:
                print(f"    instance {i}: n_variables says {declared}, "
                      f"model has {inst.n_variables}")
                problems += 1

        # Columns match small_scale/SBLP_CA_Label/CA_answer.csv exactly, and the
        # model is deliberately NOT among them. The expanded formulation is the
        # .lp text: ~14,000 newlines across the 15 instances. CSV quoting is
        # legal but every spreadsheet tool renders it as garbage and can break
        # the quoting on re-save. The models live in the .lp files next to this
        # one, indexed by the same row number.
        rows.append({
            "Obj_label": objective,
            "X_sol_label": json.dumps(solution),
            "information": inst.information(),
        })
        parameters.append(inst.parameters())
        summary.append({
            "problem": f"Air-NRM-CA-LS/{i}",
            "flights": len(inst.flights),
            "ods": len(inst.ods),
            "variables": inst.n_variables,
            "computed_objective": f"{objective:.6f}",
            "solver": primary,
            "cross_check": agree,
        })
        cons = "/".join(f"{inst.capacity_consum[inst.short[p]]:g}"
                        for p in inst.products)
        print(f"{i:>3} {len(inst.flights):>8} {len(inst.ods):>4} {inst.n_variables:>5} "
              f"{cons:>16} {inst.capacity_fraction:>5.0%} {objective:>16,.2f} "
              f"{agree:>9}")

    print()
    if problems:
        print(f"RESULT: FAIL — {problems} inconsistency(ies) above. Nothing written.")
        return 1
    if args.check:
        print("RESULT: PASS (--check: nothing written).")
        return 0

    args.out_dir.mkdir(parents=True, exist_ok=True)

    # A spreadsheet cell holds at most 32,767 characters. Anything longer is
    # still valid CSV but unreadable in Excel/Numbers, which is how the first
    # two attempts at this file shipped broken. Fail rather than write it.
    frame = pd.DataFrame(rows)
    EXCEL_CELL_LIMIT = 32767
    oversize = {
        col: int(frame[col].astype(str).str.len().max())
        for col in frame.columns
        if frame[col].astype(str).str.len().max() > EXCEL_CELL_LIMIT
    }
    newlines = {
        col: int(frame[col].astype(str).str.count("\n").sum())
        for col in frame.columns
        if frame[col].astype(str).str.count("\n").sum() > 0
    }
    if oversize or newlines:
        for col, n in oversize.items():
            print(f"REFUSING TO WRITE: column {col!r} reaches {n:,} characters, "
                  f"over the {EXCEL_CELL_LIMIT:,} a spreadsheet cell holds")
        for col, n in newlines.items():
            print(f"REFUSING TO WRITE: column {col!r} contains {n:,} embedded "
                  f"newlines; move that content to its own file")
        return 1

    answer = args.out_dir / "CA_answer.csv"
    frame.to_csv(answer, index=False)
    print(f"wrote {answer}")

    params = args.out_dir / "CA_parameters.json"
    params.write_text(json.dumps(parameters, indent=1))
    print(f"wrote {params}")

    # Same shape as run_all_*_obj.py's reports, so the objectives can be read
    # without opening the label directory.
    report = REPO_ROOT / "output" / "spreadsheet" / "airnrm_ca_ls_objectives.csv"
    report.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(summary).to_csv(report, index=False)
    print(f"wrote {report}")
    if primary != "highs":
        print(f"wrote {len(rows)} .lp files into {args.out_dir}")
    else:
        print("WARNING: HiGHS cannot emit .lp files, so Model_label is empty "
              "and no Label-model can be produced. Rerun with Gurobi or COPT.")
    print()
    print("Next:")
    print("  1. add the large_scale pair to link_air_nrm_labels.py:PAIRS, then")
    print("     python link_air_nrm_labels.py --check && python link_air_nrm_labels.py")
    print("  2. drop `Air-NRM-CA-LS: {gold_objective: null}` from exp_config.yaml")
    return 0


